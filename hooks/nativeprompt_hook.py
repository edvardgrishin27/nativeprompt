#!/usr/bin/env python3
"""UserPromptSubmit-хук для Claude Code: на КАЖДЫЙ промпт подмешивает улучшенную
версию + правила текущей модели (additionalContext). Сам текст промпта НЕ заменяет
(ограничение Claude Code) — Claude видит рядом оригинал и улучшенную версию.

Дизайн: молчит на коротких/хороших промптах (не засоряет). Любая ошибка → тихо
ничего (никогда не ломает отправку промпта).

Отдельно — БЮДЖЕТ. Хук висит на каждом промпте, значит его контекст платится
каждый раз, и это единственная величина про инструмент, которую можно назвать
без риска соврать: она меряет ЦЕНУ, а не пользу. Поэтому размер подмешиваемого
блока ограничен потолком (`ПОТОЛОК_КОНТЕКСТА`), а порядок урезания зафиксирован
и режет только НАШИ блоки — текст пользователя либо цел, либо его нет вовсе.

Подключение: см. README-блок ниже / settings.json.
"""

import json
import os
import sys

#: Потолок контекста, который хук подмешивает к промпту, в символах.
#:
#: Число не из головы: замер по корпусу проекта (~40 живых промптов × модели)
#: давал худший случай 3528 символов — и рос сам собой, потому что его никто не
#: сторожил (в момент, когда потолок задумывался, тот же замер давал 3016: с тех
#: пор к каждому совету добавилась строка «неприменимо: …», и цена выросла на
#: пятьсот символов молча). Потолок ниже худшего случая намеренно: он обязан
#: РЕЗАТЬ, иначе он не потолок, а комментарий. Символы, а не токены: токенизатор
#: у каждой модели свой и в стандартной библиотеке его нет, а выдуманный
#: коэффициент «символы → токены» был бы ровно той цифрой, которую этот проект
#: печатать не имеет права.
ПОТОЛОК_КОНТЕКСТА = 2400

#: Сколько советов показываем: обычно и после урезания.
_СОВЕТОВ_ОБЫЧНО = 6
_СОВЕТОВ_УРЕЗАННО = 3

#: Последняя ступень урезания. Ступени идут строго по порядку 0 → 3:
#:   0 — ничего не урезано;
#:   1 — снят блок «как запускать» (рекомендация харнесса);
#:   2 — плюс хвост списка советов сверх трёх;
#:   3 — плюс блок «улучшенная версия» ЦЕЛИКОМ.
#: Порядок именно такой, потому что он идёт от самого дешёвого к самому дорогому
#: для пользователя: команда запуска выводится и отдельной командой `improve`,
#: четвёртый-шестой советы — хвост уже отсортированного по важности списка, а
#: улучшенная версия — то, ради чего хук существует, и уходит последней.
_ПОСЛЕДНЯЯ_СТУПЕНЬ = 3


def _корни_чужих_окружений():
    """Куда pipx и uv кладут свои изолированные окружения.

    Живой отзыв: «поставил хук по раздатке, а он молчал всегда». Человек сделал
    `pipx install nativeprompt` — это первая строка в нашей же инструкции по
    установке, — а хук в settings.json запускается системным `python3`, который
    чужого окружения не видит. Раскладка у pipx и uv разная и зависит от системы,
    поэтому перекладывать её на пользователя строкой вида
    ~/Library/Application Support/pipx/venvs/... нельзя: путь машинозависимый
    и ломается при переустановке.
    """
    дом = os.path.expanduser("~")
    pipx = os.environ.get("PIPX_HOME") or (
        os.path.join(дом, "Library", "Application Support", "pipx") if sys.platform == "darwin"
        else os.path.join(дом, "pipx") if os.name == "nt"
        else os.path.join(дом, ".local", "share", "pipx"))
    uv = os.environ.get("UV_TOOL_DIR") or (
        os.path.join(os.environ.get("APPDATA", дом), "uv", "tools") if os.name == "nt"
        else os.path.join(дом, ".local", "share", "uv", "tools"))
    return [os.path.join(pipx, "venvs", "nativeprompt"), os.path.join(uv, "nativeprompt")]


def _site_packages(вэнв):
    """site-packages внутри окружения, если пакет там правда лежит."""
    import glob as _glob
    шаблоны = [
        os.path.join(вэнв, "lib", "python*", "site-packages"),   # posix
        os.path.join(вэнв, "Lib", "site-packages"),              # windows
    ]
    for шаблон in шаблоны:
        for site in sorted(_glob.glob(шаблон)):
            if os.path.isdir(os.path.join(site, "nativeprompt")):
                return site
    return None


def _искать_в_чужих_окружениях():
    """Найти site-packages с пакетом в окружении pipx или uv.

    Третий путь, через команду `nativeprompt` в PATH, идёт последним: у homebrew
    и у ручных обёрток она может быть простым скриптом, который в venv не ведёт.
    """
    for вэнв in _корни_чужих_окружений():
        site = _site_packages(вэнв)
        if site:
            return site
    try:
        import shutil as _shutil
        команда = _shutil.which("nativeprompt")
        if команда:
            # <venv>/bin/nativeprompt → <venv>
            site = _site_packages(os.path.dirname(os.path.dirname(os.path.realpath(команда))))
            if site:
                return site
    except Exception:
        pass
    return None


#: Жалоба печатается один раз за процесс: хук висит на каждом промпте, и
#: повторять её значит засорять вывод ровно так же, как засорял бы сам совет.
_ПОЖАЛОВАЛИСЬ = []


def _пожаловаться_один_раз():
    """Сказать вслух, что пакета нет.

    Тихий ноль — правильное поведение при любой ошибке РАБОТЫ: сломать отправку
    промпта хук не имеет права. Но когда пакета просто нет, молчание неотличимо
    от «промпт хороший, править нечего», и человек полдня думает, что инструмент
    работает. Это единственное место, где хук говорит вслух.
    """
    if _ПОЖАЛОВАЛИСЬ:
        return
    _ПОЖАЛОВАЛИСЬ.append(True)
    sys.stderr.write(
        "nativeprompt: пакет не найден, хук пропускает ход. "
        "Поставьте `pipx install nativeprompt` либо укажите путь к клону "
        "репозитория в переменной NATIVEPROMPT_HOME.\n")


def _find_package():
    """Найти пакет nativeprompt, не завися от машины автора.

    Порядок: уже установлен → окружения pipx и uv → каталог этого хука (клон
    репозитория) → NATIVEPROMPT_HOME → CLAUDE_PROJECT_DIR. Хук должен работать
    и у того, кто склонировал репозиторий куда угодно, и у того, кто поставил
    пакет одной командой и клона в глаза не видел.
    """
    try:  # уже установлен в окружение
        import nativeprompt  # noqa: F401
        return None
    except ImportError:
        pass
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # <repo>/hooks/.. = <repo>
    candidates = [
        here,
        os.environ.get("NATIVEPROMPT_HOME", ""),
        os.environ.get("CLAUDE_PROJECT_DIR", ""),
    ]
    for c in candidates:
        if c and os.path.isdir(os.path.join(os.path.expanduser(c), "nativeprompt")):
            return os.path.expanduser(c)
    чужое = _искать_в_чужих_окружениях()
    if чужое:
        return чужое
    _пожаловаться_один_раз()
    return None


def _находки(rep):
    """Советы, которые хук показывает.

    always-правила сюда не идут: они горят на каждом промпте этого поколения и
    в подмешиваемом на КАЖДЫЙ промпт блоке были бы чистой платой без сигнала.
    """
    return [f for f in rep.get("findings", []) if not f.get("always")]


def _что_убрано(rep, ступень):
    """Что урезание сняло НА САМОМ ДЕЛЕ, для честной пометки.

    Считаем по факту, а не по номеру ступени. Иначе пометка врёт: на ступени 1
    у промпта без рекомендации харнесса убирать нечего, а на ступени 2 с двумя
    советами «список сокращён до трёх» — это сокращение, которого не было.
    Пометка, которая называет несделанное, хуже отсутствующей: по ней человек
    ищет в выводе пропажу, которой нет.
    """
    убрано = []
    if ступень >= 1 and rep.get("harness"):
        убрано.append("без блока «как запускать»")
    всего = len(_находки(rep))
    if ступень >= 2 and всего > _СОВЕТОВ_УРЕЗАННО:
        убрано.append("советов %d из %d" % (_СОВЕТОВ_УРЕЗАННО, всего))
    if ступень >= 3:
        убрано.append("без улучшенной версии промпта")
    return убрано


def _собрать(rep, ступень):
    """Контекст на заданной ступени урезания. Ступени — см. _ПОСЛЕДНЯЯ_СТУПЕНЬ."""
    t = rep["target"]
    находки = _находки(rep)
    предел = _СОВЕТОВ_УРЕЗАННО if ступень >= 2 else _СОВЕТОВ_ОБЫЧНО
    с_улучшенной = ступень < _ПОСЛЕДНЯЯ_СТУПЕНЬ

    lines = [
        "[nativeprompt] Ваш промпт можно улучшить под %s (%s):"
        % (t.get("cli"), t.get("model_id") or t.get("family"))
    ]
    убрано = _что_убрано(rep, ступень)
    if убрано:
        # Пометка идёт ВТОРОЙ строкой, а не в конце: она про то, что читатель
        # видит неполную картину, и такое говорят до, а не после.
        lines.append("[nativeprompt] контекст урезан под потолок %d символов: %s. "
                     "Полный разбор — nativeprompt improve."
                     % (ПОТОЛОК_КОНТЕКСТА, ", ".join(убрано)))
    for f in находки[:предел]:
        lines.append("- %s — %s" % (f["title"], f["source"]))
        # Условие неприменимости идёт СРАЗУ под советом. Хук подмешивает
        # контекст на каждый промпт и истории диалога не видит: файл, названный
        # тридцать сообщений назад, для детектора не существует, и совет
        # «заскоупьте задачу» тут ложный. Совет без границы модель читает как
        # поручение; совет с границей она может отвергнуть по делу.
        if f.get("unless"):
            lines.append("  неприменимо: %s" % f["unless"])
    if с_улучшенной:
        # Текст пользователя вставляется ЦЕЛИКОМ или не вставляется вовсе.
        # Обрезать его по бюджету нельзя: половина промпта — это не короткий
        # промпт, а другой промпт, и модель пойдёт делать другую задачу.
        lines.append("\nУлучшенная версия промпта:\n%s" % rep["improved"])
    h = rep.get("harness")
    if h and ступень < 1:
        lines.append("\nКак запускать: %s — %s" % (h["command"], h["title"]))
    lines.append("\nСоветы выше — от детекторов по форме текста, не по смыслу диалога. "
                 "У каждого указано «неприменимо: …»: если это про текущий случай, совет "
                 "пропусти, промпт менять не надо.")
    if с_улучшенной:
        lines.append("\n(Действуй по улучшенной версии; недостающее в ‹…› уточни у пользователя.)")
    else:
        # Прежняя строка отсылала к блоку, которого в этом выводе больше нет, —
        # то есть стала бы ссылкой в пустоту.
        lines.append("\n(Улучшенной версии здесь нет — не поместилась в бюджет контекста. "
                     "Действуй по промпту пользователя, советы выше учти сам.)")
    return "\n".join(lines)


def build_context(rep):
    """Собрать блок, который хук подмешивает к промпту. Пустая строка — молчим.

    Вынесено из `main` не ради красоты: пока сборка жила внутри `main` рядом с
    чтением stdin и печатью JSON, измерить её длину можно было только запуском
    процесса — то есть цена хука не проверялась вовсе.

    Урезание идёт ступенями по фиксированному порядку, и на каждой ступени
    длина меряется вместе с пометкой об урезании — иначе пометка сама выносит
    результат за потолок, который только что был соблюдён.

    Если не помещается и полностью урезанный вариант — отдаём его как есть.
    Резать дальше нечего: там остаётся только НАШ текст (шапка, три совета с
    оговорками, пометка), а трогать текст пользователя ради бюджета запрещено.
    Такой случай не молчаливый: замер по корпусу держит запас в 671 символ
    символов, и тест сторожит не только потолок, но и само опубликованное
    число — иначе оно устареет ровно так же, как устарело 3016.
    """
    if rep.get("error") or not rep.get("target", {}).get("family"):
        return ""
    if not _находки(rep):
        return ""  # промпт и так по правилам — молчим
    for ступень in range(_ПОСЛЕДНЯЯ_СТУПЕНЬ + 1):
        текст = _собрать(rep, ступень)
        if len(текст) <= ПОТОЛОК_КОНТЕКСТА:
            return текст
    return текст


def main():
    try:
        raw = sys.stdin.read()
        data = json.loads(raw) if raw.strip() else {}
    except Exception:
        return 0
    prompt = data.get("prompt") or data.get("user_prompt") or ""
    if len(prompt.strip()) < 15:
        return 0

    root = _find_package()
    if root:
        sys.path.insert(0, root)
    try:
        from nativeprompt.analyze import normalize_prompt
        from nativeprompt.explain import build_report
        rep = build_report(normalize_prompt(prompt))
        context = build_context(rep)
    except Exception:
        return 0

    if not context:
        return 0

    out = {
        "hookSpecificOutput": {
            "hookEventName": "UserPromptSubmit",
            "additionalContext": context,
        }
    }
    print(json.dumps(out, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
