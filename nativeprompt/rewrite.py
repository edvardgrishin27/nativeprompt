# ── чистки (removals / softenings) ──────────────────────────────────
def outside_code(fn, text):
    """Применить чистку ко всему, КРОМЕ кода.

    Промпт часто несёт кусок кода как данные. Чистка формы не должна туда лезть:
    `print("ВАЖНО: не трогать")` превращался в `print("Важно: не трогать")` —
    инструмент молча правил строковый литерал чужой программы.
    """
    out, prev = [], 0
    for m in _CODE_SPAN.finditer(text):
        out.append(fn(text[prev : m.start()]))
        out.append(m.group(0))
        prev = m.end()
    out.append(fn(text[prev:]))
    return "".join(out)


#: Слова-усилители, которые вендор просит не кричать. Обратите внимание: ни одного
#: удаления и ни одной подстановки — только регистр.
_CAPS_WORD = re.compile(
    r"\b(КРИТИЧНО|ВАЖНО|СРОЧНО|ОБЯЗАТЕЛЬНО|ДОЛЖЕН|ДОЛЖНЫ|ОБЯЗАН|"
    r"CRITICAL|IMPORTANT|ALWAYS|NEVER|MUST|SHOULD)\b"
)


def _soften_caps(text):
    """Снять КРИК, не тронув ни одного слова по существу.

    Правило вендора — про КАПС как форму давления, а не про сами слова. Значит
    единственная безопасная операция здесь — понизить регистр. Всё остальное уже
    пробовали, и всё остальное ломалось:

      удаление слова   «ВАЖНО: рамки» → «рамки»          (обезглавленный абзац)
      удаление MUST    «Tests MUST pass» → «Tests pass»   (требование стало фактом)
      подстановка      «ты MUST run» → «нужно run»        (русское слово в английский)
                       «ОБЯЗАТЕЛЬНО почини» → «нужно почини» (аграмматично)

    Понижение регистра не может сломать ни грамматику, ни смысл, ни язык — потому
    что не меняет ни одного слова. Это и есть «безопасно по построению».
    """
    # Три знака — крик, один — обычное восклицание. Точка меняла тип фразы:
    # «Почини!!! баг» превращалось в «Почини. баг».
    text = re.sub(r"!{2,}", "!", text)

    def down(m):
        word = m.group(1)
        # Слово внутри ссылки, пути или составного имени НЕ трогаем: там регистр
        # значим. `https://EXAMPLE.com/MUST-READ` превращалось в `.../must-READ`,
        # а `MUST-README.md` — в `must-README.md`, то есть в битое имя файла на
        # системе с учётом регистра. «Регистр не может сломать смысл» верно ровно
        # до первого регистрозависимого токена.
        # Умолчание перевёрнуто: понижаем регистр, только если ОБА соседа —
        # пробел или обычная пунктуация. Чёрный список «/._-» пробивался чем
        # угодно ещё: `?level=CRITICAL`, `MODE=NEVER`, грепом по слову "MUST".
        # Перечислить все способы прицепить слово к токену нельзя, а требование
        # «вокруг пусто» проверяется одним взглядом.
        безопасно = " \t\n.,;:!?()[]{}«»"
        before = text[m.start() - 1] if m.start() else " "
        after = text[m.end()] if m.end() < len(text) else " "
        if before not in безопасно or after not in безопасно:
            return word
        # В начале строки или предложения слово остаётся с заглавной («Важно:»),
        # в середине — целиком строчное, иначе выходит «Tests Must pass».
        # Перевод строки НЕ обрезаем: после `rstrip()` он исчезал, и ветка
        # «слово в начале строки» была недостижима — «# ЗАДАЧА\nОБЯЗАТЕЛЬНО»
        # давало строчное «обязательно» в начале новой строки.
        head = text[: m.start()].rstrip(" \t")
        starts = not head or head[-1] in ".!?:;" or text[: m.start()].endswith(("\n", "\n "))
        return (word[0] + word[1:].lower()) if starts else word.lower()

    return _CAPS_WORD.sub(down, text)


def _tidy_lines(text):
    """Чистка ШВА после вырезания — и ничего сверх того.

    Два правила, оба выстраданные.

    Не переформатировать чужой текст. Отсюда ушло схлопывание двойных пробелов:
    это не шов, а вкусовщина, и она портила данные — `заменить "строку 'a  b'"`
    превращалось в `'a b'`, то есть инструкция замены становилась неверной.
    Двойной пробел, который пользователь поставил сам, инструмента не касается.

    Не трогать края. `outside_code` кормит эту функцию ОБРЕЗКАМИ, которые
    кончаются посреди строки — перед инлайн-кодом. Прежний `rstrip()` съедал
    пробел на таком краю, и «почини `run_all()`» слипалось в «почини`run_all()`».
    Поэтому ни rstrip, ни lstrip здесь нет вовсе.
    """
    out = []
    for line in text.split("\n"):
        if line.startswith(("    ", "\t")) or line.lstrip().startswith("|"):
            out.append(line)                 # отступ и таблица: пробел значим
            continue
        s = re.sub(r"[ \t]+([,.;:!?])", r"\1", line)      # пробел перед знаком
        s = re.sub(r",\s*([.!?])", r"\1", s)              # ", ." → "."
        out.append(s)
    return "\n".join(out)


def _tidy(text):
    """Прибрать шов после вырезаний, НЕ трогая разметку исходника.

    Две ошибки, которые здесь стояли и портили живые промпты.

    Первая: `re.sub(r"\\s+", " ", text)` схлопывал переводы строк вместе с пробелами.
    Промпт с заголовками и нумерованным списком возвращался одним абзацем — нумерация
    и переносы исчезали. Теперь чистка идёт ПОСТРОЧНО, разметка переживает правку.

    Вторая: `([а-яa-z0-9])\\s+([А-ЯA-Z][а-яa-z])` → `\\1. \\2` — попытка развести
    слипшиеся после вырезания предложения. Отличить склейку от имени собственного
    так нельзя: «планировщик Windows» превращался в «планировщик. Windows», «в России»
    в «в. России». Эвристика удалена целиком — тихо ломать текст хуже, чем оставить
    шов. Незакрытую строку добиваем точкой в конце, этого достаточно.

    Третья вылезла уже у построчной версии: правило «висящий союз» писалось для ШВА
    после вырезания, а построчно стало срабатывать на начале каждой строки — и
    осмысленное «Но не трогай конфиг прода» теряло противопоставление. Убрано вслед
    за склейками, по той же причине: правка вдали от места вырезания недопустима.

    Четвёртая: у чистки был СВОЙ список защищённого — ```-фенсы, отступ, таблицы —
    и он разошёлся с общей картой кода. Блок в `~~~` и инлайн-бэктики защищены не
    были, и `x  =  1` внутри них молча превращался в `x = 1`. Теперь чистка идёт
    через ту же `outside_code`, что и остальные ножи: одна карта кода на всех.
    Построчная защита отступов и таблиц осталась сверх неё — markdown-таблицу
    общая карта не знает, а пробелы в ней значимы.
    """
    text = outside_code(_tidy_lines, text)

    # Заглавная в начале и точка в конце — только у сплошного текста. У списка и
    # заголовков это чужая пунктуация: точка после «1. Первый пункт» не нужна.
    if "\n" not in text:
        text = text.strip()
        if text and text[0].islower():
            text = text[0].upper() + text[1:]
        if text and text[-1] not in ".!?:":
            text += "."
    return text


#: Указание МОДЕЛИ, как думать. Именно его правило Codex и просит убрать.
#: Голые «пошагово», «по шагам», «шаг за шагом» сюда НЕ входят: это слова о форме
#: ОТВЕТА, а не о ходе мыслей. «Опиши пошагово процесс деплоя» — заказ на пошаговую
#: инструкцию, и вырезание превращало его в «Опиши процесс деплоя», то есть меняло
#: задание. Убираем только то, что бессмысленно без модели: «думай пошагово».
_COT = re.compile(
    # Точка в голову НЕ входит: съеденная граница склеивала два предложения.
    # Голова та же, что у общего `_CUT_HEAD`: разойдясь, они гасили друг друга —
    # «а также» знал один шаблон, а пробел перед фразой съедал другой.
    r"(?i)[,;]?\s*(?:\b(?:и|а также)\s+)?(?:обязательно\s+)?"
    # `\b` перед глаголом: без неё «думай» находилось внутри «обдумай».
    r"\b(?:(?:думай|рассуждай|размышляй|подумай)\s+(?:пошагово|шаг за шагом|по шагам)|"
    r"think step by step|let'?s think(?: step by step)?|"
    r"рассуждай вслух|покажи ход мыслей|распиши (?:свои )?рассуждени\w*)"
)


#: Присоединённое слева «и», «а также», «обязательно» — часть той же вставки.
_CUT_HEAD = re.compile(r"(?:[,;]?\s*(?:\b(?:и|а также)\s+)?(?:обязательно\s+)?)$", re.I)
def cut_phrase(text, pattern, *, safe_tail=_SAFE_TAIL, head=_CUT_HEAD):
    """ЕДИНСТВЕННЫЙ способ вырезать фразу из промпта.

    Гард встроен сюда, а не вызывается по памяти в каждом ноже: в прошлый раз
    его поставили в один нож, а написанный рядом второй ушёл без него.

    Но главное — НАПРАВЛЕНИЕ гарда. Пять кругов подряд он был чёрным списком
    опасных хвостов («о», «про», «about»…), и каждый круг находил предлог, до
    которого список не дотянулся: «по поводу», «насчёт», «над», «for», «through».
    Перечислить все способы, которыми русский и английский цепляют дополнение,
    нельзя — это открытое множество.

    Поэтому умолчание перевёрнуто: режем ТОЛЬКО когда хвост доказуемо безопасен —
    конец текста, конец предложения, перевод строки, запятая, союз. Незнакомое
    слово после фразы означает «не трогать», а не «трогать». Ошибка сдвинута в
    сторону бездействия: пропущенная правка видна в отчёте как находка, а
    испорченный текст не виден никак.
    """
    out, prev = [], 0
    for m in pattern.finditer(text):
        if safe_tail and not safe_tail.match(text, m.end()):
            continue
        start = m.start()
        if head:
            h = head.search(text, 0, start)
            if h:
                start = h.start()
        out.append(text[prev:start])
        prev = m.end()
        # Разделитель остаётся ОДИН. Раньше съедались обе граничные запятые, и
        # «почини баг, думай пошагово, перепроверь себя» превращалось в «Почини
        # баг перепроверь себя» — два поручения слипались без пунктуации.
        # Хвостовой знак снимаем, только если слева уже есть свой.
        слева = "".join(out).rstrip()
        справа = text[prev] if prev < len(text) else ""
        if слева and слева[-1] in ".,;!?" and справа in ".,;":
            prev += 1
    out.append(text[prev:])
    склеено = "".join(out)
    # Фраза стояла в НАЧАЛЕ текста — ведущий разделитель остался висеть:
    # «Думай пошагово, почини баг» давало «, почини баг».
    return re.sub(r"^[\s,;.]+", "", склеено) if склеено.lstrip()[:1] in ",;." else склеено


def _strip_cot(text):
    """Убрать навязанную цепочку рассуждений — и ничего кроме неё.

    Три ошибки жили здесь по очереди. Первая: группа `(и\\s+)?` без границы слова
    съедала конечную «и» предыдущего слова — «Опиши пошагово» превращалось в «Опиш».
    Вторая: в список попали голые «пошагово» и «по шагам», которые в русском чаще
    описывают ФОРМАТ результата, а не ход мыслей. Третья: точка в голове шаблона
    съедала границу предложения, и дополнение шло к чужому глаголу.
    """
    return cut_phrase(text, _COT)


