"""Сборка и рендер отчёта: было → стало + почему (со ссылкой на правило) +
как запускать. Обучающий слой инструмента."""

import hashlib
import textwrap

from . import __version__, catalog, detect as _detect
from .analyze import analyze, mask_code, normalize_prompt, task_shape
from .harness import recommend_harness
from .rewrite import (МАРКЕР_ПЛЕЙСХОЛДЕРА, rewrite, build_metaprompt,
                      strip_insertions)

_ACTION_MARK = {"add": "[+]", "remove": "[-]", "restructure": "[~]", "warn": "[!]"}
_WIDTH = 76  # переносим сами: терминал рвёт длинные строки посреди слова
#: Маркер того, что инструмент к тексту не притронулся.
_UNTOUCHED_MARK = "[!]"


def _mark(finding, applied):
    """Маркер по ФАКТУ, а не по объявленному в правиле намерению.

    Раньше он читался прямо из `action`, и два always-правила с `action: add`
    (`fable5-ground-progress`, `opus48-encourage-subagents`) печатались тем же
    `[+]`, что и `opus5-concise`, который действительно дописывает «Ответь
    кратко». Маркер обещал добавление, которого не было: оба правила уходят
    только в мета-промпт. Теперь соврать он не может — знак действия получает
    лишь то правило, которое реально попало в `applied`.
    """
    if finding["id"] not in applied:
        return _UNTOUCHED_MARK
    return _ACTION_MARK.get(finding["action"], "[?]")


def _wrap(text, indent="   ", first=None):
    """Перенести длинный текст по словам с отступом (для читаемости в кадре)."""
    first = indent if first is None else first
    return textwrap.fill(
        str(text), width=_WIDTH,
        initial_indent=first, subsequent_indent=indent,
        break_long_words=False, break_on_hyphens=False,
    )


#: Значение, которое печатается на месте отсутствующих данных. Пустая строка в
#: отчёте читается как поломка вывода, «—» — как «этого нет», и в отчёте так уже
#: пишется источник детекта.
_НЕТ_ДАННЫХ = "—"


def _дата_снимка_доков():
    """Дата снимка вендорских доков — версия манифеста `rules/_sources.json`.

    Это НЕ то же самое, что `rules_version` семейства: там записано, когда
    человек в последний раз правил правила, а здесь — к какому дню относится
    сверка со страницами вендора, которую гоняет `nativeprompt update`.
    Разошлись эти две даты — значит доки перечитывали, а правила не трогали, и
    по одному отчёту это видно.

    Манифест едет в пакет вместе с правилами (`rules/*.json`), но читаем его
    защищённо: карточка воспроизводимости не имеет права уронить отчёт, ради
    которого её собирают.
    """
    try:
        return catalog.load_sources().get("rules_version") or _НЕТ_ДАННЫХ
    except (OSError, ValueError, catalog.RulesError):
        return _НЕТ_ДАННЫХ


def build_meta(prompt, target, shape, findings, applied):
    """Карточка воспроизводимости: по чему именно получен ЭТОТ отчёт.

    Новых данных здесь нет ни одного — всё уже посчитано пайплайном и просто
    не печаталось. Смысл в том, что два отчёта от разных версий инструмента и
    разных версий шпаргалки внешне неразличимы: та же шапка, тот же список
    советов. Через месяц человек не отличит вывод, собранный до правки правил,
    от вывода после неё, и спор «у меня выдавало другое» не решается ничем.

    Что в карточке и зачем:

      tool_version      — версия пакета: правила правит человек, но их читает
                          КОД, и поведение менялось между версиями;
      family            — по какой шпаргалке шёл разбор;
      rules_version     — версия правил этого семейства (rules/<family>.json);
      docs_snapshot     — к какому дню относится сверка с доками вендора;
      generation        — поколение модели, если оно определилось;
      generation_source — ПО КАКОМУ признаку. Ключевое поле: при
                          `alias-unresolved` («opus», «sonnet» без версии)
                          применялись правила СЕМЕЙСТВА, а не поколения, и без
                          этой пометки отчёт выглядит так же, как отчёт по
                          точно названной модели;
      shape             — форма задачи, от неё зависит и рекомендация харнесса,
                          и часть правил;
      findings/applied  — какие правила сработали и какие из них инструмент
                          закрыл сам. Списки id, а не тексты: id стабилен, а
                          формулировку правила человек правит;
      prompt_sha256     — двенадцать первых символов sha256 исходного промпта.

    Про хэш отдельно. Он нужен, чтобы сверить «тот ли это промпт», не таская за
    отчётом сам промпт: в промптах бывают пути, имена внутренних сервисов и
    куски логов, и вклеивать их в баг-репорт целиком человек не станет.
    Двенадцать шестнадцатеричных символов — 48 бит; это метка для сверки, а не
    доказательство и не защита: полный текст по ней не восстанавливается, но и
    от подбора коллизии она не спасает. Хэш считаем от НОРМАЛИЗОВАННОГО текста
    (`report["original"]`) — того самого, который видели детекторы; хэш от
    сырого аргумента расходился бы у двух дверей CLI на одном и том же промпте.
    """
    правила = catalog.load_family(target["family"])
    return {
        "tool_version": __version__,
        "family": target["family"],
        "rules_version": правила.get("rules_version") or _НЕТ_ДАННЫХ,
        "docs_snapshot": _дата_снимка_доков(),
        "generation": target.get("generation") or _НЕТ_ДАННЫХ,
        "generation_source": target.get("generation_source") or _НЕТ_ДАННЫХ,
        "shape": shape,
        "findings": [f["id"] for f in findings],
        "applied": list(applied),
        "prompt_sha256": hashlib.sha256(prompt.encode("utf-8")).hexdigest()[:12],
    }


def build_report(prompt, model=None, target=None):
    """Один вызов: детект модели → разбор → харнесс → перепись → мета-промпт.

    `target` — уже разрешённая модель. Передан — `detect.resolve` не зовём
    вовсе. Это нужно самопроверке (`verify_delta`): она гоняет отчёт второй
    раз, а `resolve` читает окружение и конфиги, и его повторный вызов вправе
    вернуть другое семейство — сменилась переменная среды, поправили
    ~/.claude/settings.json. Тогда две половины самопроверки сравнивали бы
    находки по РАЗНЫМ наборам правил, и расхождение выглядело бы как дефект
    инструмента, которым оно не является.

    Умолчание `None` оставлено ради совместимости: у людей вызов хука уже
    прописан в settings.json, и обе прежние формы (`build_report(p)` и
    `build_report(p, "claude-opus-5")`) работают как работали.
    """
    # Нормализуем ЗДЕСЬ, а не в каждой двери: аргумент CLI приходил сырым, и
    # те же байты через `improve "…"` и через stdin давали разные отчёты —
    # пустые строки в начале дотягивали текст до порога «многочастный», и
    # XML-обёртка применялась к промпту, который по собственному критерию
    # многочастным не был.
    prompt = normalize_prompt(prompt)
    if target is None:
        target = _detect.resolve(model)
    report = {"original": prompt, "target": target}
    if not target.get("family"):
        # Карточки воспроизводимости у такого отчёта нет намеренно: без
        # семейства нет ни версии правил, ни поколения, ни разбора, а половина
        # карточки хуже её отсутствия — она обещает воспроизводимость, которой
        # по ней не добиться. Так же здесь ведут себя и findings, и improved.
        report["error"] = "model_unknown"
        return report
    # Форму считаем по тому же тексту, что видят детекторы: с замаскированным
    # кодом. Иначе отчёт противоречит сам себе — `analyze` уже маскировал, а
    # `task_shape` здесь читал сырой текст, и один вызов выдавал одновременно
    # «форма: trivial» и правила, которые на trivial не срабатывают.
    masked = mask_code(prompt)
    shape = task_shape(masked)
    findings = analyze(prompt, target)
    harness_rec = recommend_harness(masked, target, shape)
    rw = rewrite(prompt, target, findings, shape)
    report.update(
        {
            "shape": shape,
            "findings": findings,
            "harness": harness_rec,
            "improved": rw["improved"],
            "applied": rw["applied"],
            # Расписка сборщика: какие куски improved дописал сам инструмент.
            # Нужна самопроверке, чтобы второй прогон не принял наши же
            # вставки за текст автора (см. rewrite.strip_insertions).
            "insertions": rw["insertions"],
            "metaprompt": build_metaprompt(prompt, target, findings, harness_rec),
            # Карточка воспроизводимости. Собирается ПОСЛЕДНЕЙ и из готового:
            # своих вычислений у неё нет, иначе она сообщала бы не о том
            # отчёте, к которому приложена.
            "meta": build_meta(prompt, target, shape, findings, rw["applied"]),
        }
    )
    return report


#: Три корзины самопроверки. Порядок фиксирован: он же в выводе `--verify`.
_КОРЗИНЫ = ("closed", "left", "introduced")


def verify_delta(report):
    """Прогнать те же детекторы по СОБСТВЕННОМУ результату и разложить правила
    на три корзины: `closed` / `left` / `introduced` (списки id).

    Чистая функция: ничего не печатает, ничего не читает из окружения, второй
    раз модель не определяет. Смысл корзин:

      closed     — находка была в промпте автора и в его тексте больше не
                   горит. Снять её мог только нож: понижение КАПС и снятие
                   вежливой обёртки — всё, что инструмент правит в тексте.
      left       — находка осталась. Это НОРМА, а не недоработка: правила,
                   которые требуют понимания смысла, инструмент по договору
                   помечает, а не режет. Сюда же попадает правило, ответом на
                   которое была наша вставка (секция-плейсхолдер, XML-обёртка):
                   содержание в плейсхолдер пишет человек, и пока он этого не
                   сделал, находка горит честно.
      introduced — находки не было, а в результате она есть. Вот это дефект:
                   инструмент сам внёс в текст то, на что сам же ругается.

    Второй прогон идёт через ту же дверь `build_report`, а не через собранную
    здесь копию пайплайна: иначе самопроверка проверяла бы ДРУГОЙ инструмент.
    Модель ему передаётся уже разрешённой (`target=`) — почему, написано в
    докстринге `build_report`.

    Текст на второй прогон отдаётся без собственных вставок инструмента (см.
    `rewrite.strip_insertions`): детекторы должны судить о тексте автора, а не
    о наших плейсхолдерах. Иначе корзины врут в обе стороны сразу — и
    `introduced` набирает находок на пустом месте, и `left` теряет их, потому
    что слово «тест» из нашего же плейсхолдера читается как заказанная
    автором проверка.
    """
    if report.get("error"):
        # Модель не определилась — сравнивать нечего и не с чем.
        return {корзина: [] for корзина in _КОРЗИНЫ}
    было = {f["id"] for f in report["findings"]}
    текст = strip_insertions(report["improved"], report.get("insertions") or [])
    стало = {f["id"] for f in build_report(текст, target=report["target"])["findings"]}
    return {
        "closed": sorted(было - стало),
        "left": sorted(было & стало),
        "introduced": sorted(стало - было),
    }


def _добавь_неприменимость(out, finding, indent, first):
    """Напечатать рядом с находкой условие, при котором совет НЕ применяется.

    Детекторы здесь — регулярки, и ошибаются они по построению: истории
    диалога они не видят, смысла не понимают. Восемь кругов ревью показали,
    что делать их точнее — дорога без конца; дешевле сделать ошибку
    безвредной. Поэтому у совета печатается его же граница: увидел своё
    условие — пропустил совет, и ложное срабатывание не стоило ничего.
    """
    if not finding.get("unless"):
        return
    out.append(_wrap(finding["unless"], indent=indent, first=first + "неприменимо: "))


#: Ровно та строка, которую человек читает вместо мета-промпта.
ОТКАЗ = ("Промпт соответствует правилам, которые инструмент умеет проверять, "
         "переписывать нечего.")


def nothing_to_do(report):
    """Правда, когда переписывать нечего — и мета-промпт печатать не надо.

    Чистая функция от отчёта: ничего не печатает, в окружение не смотрит,
    отчёт не мутирует.

    Истина в двух случаях:

      • не-always находок нет вовсе — правила, которые инструмент умеет
        проверять, по этому промпту молчат;
      • все сработавшие правила инструмент УЖЕ закрыл сам, среди них нет ни
        одного с `action: warn` и ни одно не оставило вам плейсхолдер ‹…› —
        значит не осталось ни одного совета, который ждёт вашего решения.

    Зачем это нужно. Мета-промпт — инструкция «перепиши промпт под модель»,
    и печатался он всегда, даже с заглушкой «(существенных правок правила не
    требуют)». Человек получал поручение переписать то, что переписывать не
    надо, — а модель, которой он это поручение отдаст, работу найдёт, потому
    что её попросили. Отказ дешевле любой правки ради правки.

    Условие про `warn` стоит отдельно, хотя сегодня warn-правило в `applied`
    попасть не может: ветки в переписчике у него нет по договору («помечать,
    а не резать»). Появится такая ветка — и без этой строчки предупреждение,
    требующее вашего решения, молча уехало бы вместе с мета-промптом.

    Отчёт с ошибкой (модель не определилась) — не «нечего переписывать», а
    «разбора не было»: утверждать по нему нечего, поэтому False.

    Отдельно про «применено». Вставленный нами плейсхолдер ‹…› применением НЕ
    считается: правило от него не закрывается, оно передано человеку. Так
    считает и самопроверка `verify_delta` — такие правила у неё лежат в корзине
    «оставлено вам», то есть горят по-прежнему. Без этой оговорки две половины
    одного инструмента говорили бы разное об одном промпте: «Не мог бы ты
    ОБЯЗАТЕЛЬНО починить баг в логине…» на Fable 5 закрывается пятью правками,
    три из которых — секции ‹уточните: …›, и отказ «переписывать нечего» стоял
    бы прямо над текстом, который без вас не дописан. Плейсхолдеры считаем по
    расписке сборщика (`insertions`), а не по всему тексту: угловые скобки в
    промпте мог написать и сам автор, и его текст — не наша недоделка.
    """
    if report.get("error"):
        return False
    сработали = [f for f in report.get("findings", []) if not f.get("always")]
    if not сработали:
        return True
    if any(f.get("action") == "warn" for f in сработали):
        return False
    применены = set(report.get("applied") or [])
    if not all(f["id"] in применены for f in сработали):
        return False
    return not _есть_наш_плейсхолдер(report)


def _есть_наш_плейсхолдер(report):
    """Оставил ли инструмент в тексте ‹…›, дописывать которые человеку.

    Смотрим только на СВОИ куски — по расписке сборщика (`insertions`), той же,
    которой пользуется самопроверка. Угловые скобки мог написать и автор, и
    его текст нашей недоделкой не является.
    """
    текст = report.get("improved") or ""
    свои = "".join(текст[int(a):int(b)] for a, b in (report.get("insertions") or []))
    return МАРКЕР_ПЛЕЙСХОЛДЕРА in свои


def render_meta(meta):
    """Карточка воспроизводимости одной компактной строкой.

    Списков id здесь нет намеренно, только их размер: сами id напечатаны выше
    в разборе, каждый со своей ссылкой на правило, и вторая их копия строкой
    ниже — не воспроизводимость, а шум. Полный объект отдаёт `--json`, он и
    предназначен для приложения к баг-репорту.

    Порядок полей — от общего к частному: чем инструмент был, по чему судил,
    что увидел, о каком тексте речь.
    """
    return _wrap(
        "воспроизводимость: nativeprompt %(tool_version)s · правила %(family)s "
        "%(rules_version)s · доки сверены %(docs_snapshot)s · поколение "
        "%(generation)s (%(generation_source)s) · форма %(shape)s · сработало "
        "%(сколько_findings)d, применено %(сколько_applied)d · промпт sha256 "
        "%(prompt_sha256)s"
        % dict(meta,
               сколько_findings=len(meta["findings"]),
               сколько_applied=len(meta["applied"])),
        indent="  ", first="")


def _rule(line):
    return line


def render_report(report, show_metaprompt=True):
    t = report["target"]
    out = []
    bar = "─" * 66

    if report.get("error") == "model_unknown":
        out.append("Не удалось определить модель.")
        out.append(
            "Укажите её явно: nativeprompt improve \"<промпт>\" --model claude-opus-5"
        )
        out.append("(или --model gpt-5.6 / codex). Семейства: %s." % ", ".join(catalog.available_families()))
        return "\n".join(out)

    # Отказ печатается ПЕРВЫМ блоком: это главное, что человеку нужно узнать
    # про свой промпт, и оно не должно теряться под разбором.
    нечего = nothing_to_do(report)
    if нечего:
        out.append(ОТКАЗ)
        закрыто = [f["id"] for f in report["findings"]
                   if not f.get("always") and f["id"] in report["applied"]]
        if закрыто:
            # Список находок ниже не пуст, и без этой строчки отказ выглядел бы
            # как противоречие самому себе: «нечего», а под ним три пункта.
            out.append(_wrap("сработавшее инструмент закрыл сам: %s — умной переписи "
                             "тут работы не осталось." % ", ".join(закрыто),
                             indent="  ", first="  "))
        out.append(_wrap("мета-промпт не печатаю: отдать модели поручение «перепиши» "
                         "там, где переписывать нечего, — значит получить правку ради "
                         "правки.", indent="  ", first="  "))
        out.append("")

    gen = (" · " + t["generation"]) if t.get("generation") else ""
    mid = (" (" + t["model_id"] + ")") if t.get("model_id") else ""
    out.append(bar)
    out.append("МОДЕЛЬ: %s%s%s" % (t.get("cli", t["family"]), mid, gen))
    out.append("определено: %s" % t.get("source", "—"))
    if t.get("context_1m"):
        out.append("контекст: 1M (суффикс [1m] — не теряйте его при смене модели)")
    if t.get("generation_source") == "alias-unresolved":
        out.append(
            "⚠ модель задана алиасом — точная версия зависит от провайдера и плана,\n"
            "  поэтому применяю правила СЕМЕЙСТВА. Для версионных правил укажите\n"
            "  полное имя: --model claude-opus-5"
        )
    elif t.get("generation_source") == "unknown-id" and t.get("family"):
        out.append("⚠ версия модели неизвестна — применяю правила семейства")
    if report.get("meta"):
        # Карточка стоит в шапке, а не в подвале, ровно по одной причине: под
        # отчётом лежит мета-промпт, который человек выделяет и копирует
        # целиком, и строка про версии уехала бы вместе с ним в чужую модель.
        out.append(render_meta(report["meta"]))
    out.append(bar)

    findings = [f for f in report["findings"] if not f.get("always")]
    always = [f for f in report["findings"] if f.get("always")]
    out.append("")
    if findings:
        # «сначала важное» — не украшение заголовка, а обещание: находки
        # отсортированы по priority (контракт результата и границы задачи →
        # режим запуска и структура → косметика), и читать их сверху вниз
        # теперь осмысленно.
        out.append("ЧТО УЛУЧШИТЬ (%d, сначала важное):" % len(findings))
        for i, f in enumerate(findings, 1):
            mark = _mark(f, report["applied"])
            out.append(_wrap(f["title"], indent="      ",
                             first="%d. %s " % (i, mark)))
            out.append(_wrap(f["why"], indent="      ", first="   почему: "))
            _добавь_неприменимость(out, f, indent="      ", first="   ")
            out.append("   правило: %s" % f["source"])
    else:
        out.append("ЧТО УЛУЧШИТЬ: существенных правок правила не требуют.")
    for f in always:
        mark = _mark(f, report["applied"])
        out.append(_wrap(f["title"], indent="    ", first="%s " % mark))
        _добавь_неприменимость(out, f, indent="    ", first="    ")
        out.append("    правило: %s" % f["source"])

    out.append("")
    out.append(bar)
    out.append("УЛУЧШЕННЫЙ ПРОМПТ (детерминированная правка):")
    out.append(bar)
    out.append(report["improved"])
    out.append(bar)

    h = report.get("harness")
    if h:
        out.append("")
        out.append("КАК ЗАПУСКАТЬ (%s) — форма задачи: %s" % (h["cli"], h["shape"]))
        out.append("  → %s" % h["command"])
        out.append(_wrap(h["title"], indent="  "))
        out.append(_wrap(h["why"], indent="  ", first="  почему: "))
        if h.get("source"):
            out.append("  правило: %s" % h["source"])
        for extra in h.get("anytime") or []:
            out.append("")
            out.append("  в любой момент: %s" % extra["command"])
            out.append(_wrap(extra["title"], indent="  "))
            if extra.get("source"):
                out.append("  правило: %s" % extra["source"])

    # `нечего` посчитано выше одним вызовом: два вызова одной чистой функции
    # дали бы тот же ответ, но напечатанный отказ и напечатанный мета-промпт
    # обязаны следовать ОДНОМУ решению, а не двум одинаковым по случайности.
    if show_metaprompt and not нечего:
        out.append("")
        out.append(bar)
        out.append("МЕТА-ПРОМПТ для «умной» переписи (вставьте своей же модели):")
        out.append(bar)
        out.append(report["metaprompt"])

    return "\n".join(out)


#: Подпись каждой корзины: что она значит человеку, который видит её впервые.
_ПОДПИСЬ_КОРЗИНЫ = {
    "closed": "закрыто (в вашем тексте находки больше нет)",
    "left": "оставлено вам (правило горит по-прежнему — это норма)",
    "introduced": "ВНЕСЕНО ИНСТРУМЕНТОМ (находки не было, а после правки есть)",
}


def render_verify(delta):
    """Три корзины на экран. Ни «лучше», ни процентов: это счёт правил.

    Оценивать качество текста инструмент не умеет и не берётся — он умеет
    сказать, сколько СВОИХ ЖЕ правил горит до и после правки. Любая цифра со
    знаком качества («стало лучше на 40%») была бы выдумкой поверх счёта.

    Счёт идёт по тексту АВТОРА: собственные вставки инструмент из него
    вычитает, иначе он проверял бы сам себя своими же плейсхолдерами. Отсюда и
    смысл второй корзины — правило, ответом на которое была наша вставка
    (секция-плейсхолдер, XML-обёртка), остаётся «оставлено вам»: содержание в
    плейсхолдер пишете вы, и до тех пор находка честно горит.
    """
    bar = "─" * 66
    out = ["", bar, "САМОПРОВЕРКА: те же детекторы, прогнанные по результату", bar]
    out.append("правил, которые инструмент умеет проверять:")
    out.append("закрыто %d, оставлено вам %d, внесено инструментом %d"
               % tuple(len(delta[к]) for к in _КОРЗИНЫ))
    out.append(_wrap("считаем по вашему тексту: собственные вставки (плейсхолдеры, "
                     "заметки, XML-обёртку) инструмент из счёта вычитает. Это счёт "
                     "правил, а не оценка текста.", indent="", first=""))
    for корзина in _КОРЗИНЫ:
        out.append("")
        out.append("%s:" % _ПОДПИСЬ_КОРЗИНЫ[корзина])
        if not delta[корзина]:
            out.append("  —")
            continue
        for rule_id in delta[корзина]:
            out.append("  • %s" % rule_id)
    if delta["introduced"]:
        out.append("")
        out.append(_wrap("внесённое инструментом — дефект инструмента, а не ваша работа: "
                         "сообщите о нём в issue вместе с исходным промптом.",
                         indent="", first=""))
    return "\n".join(out)
