def _c_repetition(p, low, t):
    """Подряд идущие одинаковые предложения.

    Правило (`codex-lean`) теперь только предупреждает: точность детектора
    больше не привязана к механике правки в `rewrite` — своя логика вместо
    вызова туда. Сравнение устойчиво к трём записям одного и того же
    предложения: с финальной точкой и без, с пробелом после точки и без —
    обе стороны просто срезаются перед сравнением. Голый маркер списка
    («2.», «-») предложением не считается и цепочку повтора не прерывает.
    """
    last = None
    for line in p.split("\n"):
        for part in re.split(r"(?<=[.!?])\s*", line):
            part = part.strip()
            if not part or re.fullmatch(r"(?:\d+[.)]|[-*•])", part):
                continue                     # маркер списка — пунктуация, не предложение
            key = part.rstrip(".!?").lower()
            if len(key) > 12 and key == last:
                return True
            last = key
    return False


