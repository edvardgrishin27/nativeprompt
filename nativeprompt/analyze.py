#: Код как ДАННЫЕ: закрытый блок, НЕзакрытый блок до конца текста, инлайн-код.
#: Единственное определение на весь пакет — `rewrite` импортирует это же. Раньше
#: их было два под одним именем и с разной семантикой: `rewrite` знал про
#: незакрытый блок, `analyze` — нет, и на оборванном промпте детектор снова видел
#: не тот текст, что переписчик.
#: Прямые двойные кавычки тоже данные: `замени "x ; y" на "x; y"` — это
#: инструкция замены, и правка пробела внутри превращала её в тождество.
CODE_SPAN = re.compile(
    # Кавычки ходовых видов — ёлочки, лапки, прямые двойные — а не только
    # прямые двойные: белый список из одного вида — тот же чёрный список
    # наизнанку. Ёлочки в русском стандартны.
    #
    # Одинарных кавычек здесь больше НЕТ — это откат, а не пропуск. В
    # английском апостроф чаще часть слова, чем кавычка: "Fix the bug in
    # @src/auth.py. Don't guess, run the tests until it's green." — спан между
    # "Don't" и "it's" накрывал «run the tests» целиком, и claude-verification
    # срабатывало вслепую, хотя автор уже заказал прогон тестов. Отличить
    # апостроф от настоящей одинарной кавычки по форме нельзя — тот же класс
    # задачи, что и у ножей, и то же решение: не трогать. Ёлочки, лапки и
    # прямые двойные кавычки апострофом не путаются — их защита остаётся.
    r'`[^`\n]+`'
    r'|«[^»\n]{1,120}»|„[^“\n]{1,120}“',
    re.S,
)
#: Прямые двойные кавычки СЧИТАЮТСЯ ПАРАМИ (см. `_прямые_кавычки`), а не
#: регуляркой: у них открывающая и закрывающая неразличимы, и жадный поиск
#: спаривал ЗАКРЫВАЮЩУЮ кавычку одной пары с ОТКРЫВАЮЩЕЙ следующей. Стоило
#: первой паре не пройти по длине или упереться в перевод строки — и маска
#: накрывала прозу между двумя цитатами, а сам цитируемый текст оставляла
#: детекторам. Крик и «перепроверь себя» в такой прозе инструмент не видел.
_ПРЯМАЯ_КАВЫЧКА = '"'
#: Тот же лимит, что у остальных кавычек: длинная «цитата» — почти всегда не
#: цитата, а два разных места текста.
_ПРЕДЕЛ_КАВЫЧКИ = 120


def _прямые_кавычки(text, куски):
    """Области прямых кавычек — строго парами, и только вне другого кода.

    Девятнадцатый круг показал две беды сразу. Кавычка ВНУТРИ бэктик-спана
    (``Убери `print("` из кода и замени "текст ВАЖНО" …``) участвовала в
    счёте и сдвигала все пары: «областью» становился кусок прозы, а настоящая
    цитата оставалась без защиты, и нож правил регистр внутри неё. Поэтому
    считаем только по кускам, не занятым другим кодом.

    Вторая беда — НЕЧЁТНОЕ число кавычек (дюймы: «Экран 15" сломан — убери
    "СТАРЫЙ ВАЖНО блок" из конфига»). Какая кавычка лишняя, по форме не
    узнать. Значит действует общее правило проекта: не разобрал — считай
    кодом и молчи. Весь промежуток от первой кавычки до последней уходит в
    данные; цена — пропущенная находка, а не правка внутри чужой строки.
    """
    области = []
    for начало, конец in куски:
        позиции = [i for i in range(начало, конец) if text[i] == _ПРЯМАЯ_КАВЫЧКА]
        if len(позиции) % 2:
            области.append((позиции[0], позиции[-1] + 1))
            continue
        for левая, правая in zip(позиции[::2], позиции[1::2]):
            кусок = text[левая + 1:правая]
            # Пара, не похожая на цитату, областью НЕ становится — но обе её
            # кавычки потрачены, и следующая пара считается от третьей.
            if "\n" not in кусок and 1 <= len(кусок) <= _ПРЕДЕЛ_КАВЫЧКИ:
                области.append((левая, правая + 1))
    return области
#: Фенс-блоки СЮДА НЕ ВХОДЯТ — их считает `_фенс_блоки` построчно по
#: CommonMark. Семнадцатый круг показал, почему нельзя иначе: жадное
#: спаривание ранов давало маске и предикату РАЗНЫЕ границы кода, и
#: каждое расхождение было дефектом — то нож правил КАПС внутри
#: незакрытого блока, то детектор молчал на крике посреди прозы.

#: Слова-усилители, которые вендор просит не кричать. Единственное определение
#: на весь пакет — как у `CODE_SPAN` выше: своя копия у ножа (`_soften_caps` в
#: `rewrite`) и у детектора (`_c_pushy_caps`) уже расходилась, и детектор
#: печатал «[-] Убрать давящие КАПС» там, где нож не трогал ни буквы.
#: Русские слова-усилители в промпте почти никогда не бывают техническим
#: значением, английские — сплошь и рядом: уровень лога `CRITICAL`, значение
#: конфига, HTTP-метод, поле таблицы. Поэтому английское слово считается криком
#: только когда стоит заголовком — то есть за ним НА ТОЙ ЖЕ СТРОКЕ двоеточие или
#: восклицательный знак. `\s*` перешагивал перевод строки, и `!important` из CSS
#: на следующей строке превращал техническое значение в «заголовок». «Выставь уровень логирования CRITICAL» больше не понижается: понизив,
#: инструмент ломал `logger.setLevel("CRITICAL")`, а по форме крик от значения
#: не отличить — и по собственному принципу проекта это значит «не трогать».
CAPS_WORD = re.compile(
    r"\b(КРИТИЧНО|ВАЖНО|СРОЧНО|ОБЯЗАТЕЛЬНО|ДОЛЖЕН|ДОЛЖНЫ|ОБЯЗАН|ОБЯЗАНЫ)\b"
    r"|\b(CRITICAL|IMPORTANT|ALWAYS|NEVER|MUST|SHOULD)\b(?=[ \t]*[:!])"
)

#: Соседи «пустые» — пробел или обычная пунктуация. Слово с ЛЮБЫМ другим
#: соседом регистрозначимо: `MODE=CRITICAL`, `https://ex.com/MUST-READ`,
#: `MUST-README.md` — там КАПС не крик, а часть токена. Общий гард ножа
#: (`_soften_caps`) и детектора (`_c_pushy_caps`): раньше он жил только в
#: ноже, и детектор предупреждал о правке, которой не будет.
_SAFE_NEIGHBORS = " \t\n.,;:!?()[]{}«»"


def has_safe_neighbors(text, start, end):
    before = text[start - 1] if start else " "
    after = text[end] if end < len(text) else " "
    return before in _SAFE_NEIGHBORS and after in _SAFE_NEIGHBORS


def mask_code(text):
    """Заменить содержимое код-блоков пробелами, сохранив длину и переводы строк.

    Детектор и переписчик обязаны видеть ОДИН текст. Иначе получается ложное
    предупреждение: фраза «перепроверь себя» внутри строкового литерала —
    `msg = "перепроверь себя и попробуй снова"` — заставляла правило сработать,
    хотя переписчик к коду не притрагивается. Длину сохраняем, чтобы спаны,
    посчитанные по маскированному тексту, годились для исходного.
    """
    куски, прошлый = [], 0
    for начало, конец in code_regions(text):
        if начало < прошлый:
            continue                   # вложенная область уже покрыта
        куски.append(text[прошлый:начало])
        куски.append("".join("\n" if ch == "\n" else " " for ch in text[начало:конец]))
        прошлый = конец
    куски.append(text[прошлый:])
    return "".join(куски)


#: Строка, открывающая блок кода. Кроме отступа допускается маркер списка:
#: внутри пункта отступ отсчитывается от края СОДЕРЖИМОГО пункта, поэтому
#: «- ```» открывает блок, а «  ```» его закрывает. Без этого закрывающий фенс
#: списочного пункта читался как ещё один открывающий, и инструмент молча
#: замолкал на промпте, который кончается обычной прозой.
#: Префикс строки: цитаты и маркеры списка в ЛЮБОМ порядке. Раньше знали
#: только «цитата, потом список», и на «- > ```» открывающий фенс был не виден
#: вовсе — а нож правил тело блока как прозу.
_ПРЕФИКС = r"(?P<pre>(?:[ ]{0,3}(?:>[ ]?|(?P<список>[-*+]|\d{1,9}[.)])[ ]{1,4}))*[ ]{0,3})"
_ФЕНС_ОТКР = re.compile(r"^" + _ПРЕФИКС + r"(?P<ран>`{3,}|~{3,})(?P<инфо>[^\n]*)$")
#: Закрывающая строка: только ран и пробелы, никакой info string.
_ФЕНС_ЗАКР = re.compile(r"^" + _ПРЕФИКС + r"(?P<ран>`{3,}|~{3,})[ \t]*$")
#: Отступной код-блок: четыре пробела и текст, который не начинает пункт
#: списка. CommonMark 4.4. Без него «    ВАЖНО: не удалять» под списочным
#: пунктом инструмент считал прозой и правил — то есть при неразобранной
#: разметке падал в «править», а обещал падать в «молчать».
_ОТСТУПНЫЙ_КОД = re.compile(
    r"^(?:[ ]{0,3}>[ ]?)*(?:[ ]*\t|[ ]{4,})(?![-*+][ ]|\d{1,9}[.)][ ])\S")
#: HTML-комментарий: внутри него разметка не действует, значит ``` там — текст.
_HTML_ОТКР = re.compile(r"^[ ]{0,3}<!--")
#: Строка-цитата: `>` в начале. Внутри — чужая речь, не наш текст.
_ЦИТАТА = re.compile(r"^[ ]{0,3}>")


def normalize_prompt(text):
    """Привести промпт к виду, в котором его разбирает и правит инструмент.

    ЕДИНСТВЕННАЯ нормализация на весь пакет. Раньше её роль играл `strip()`,
    расставленный в трёх местах порознь — в `rewrite`, в чтении stdin и в
    сборке мета-промпта. Двадцатый круг починил первое, двадцать первый нашёл
    два оставшихся: штатная дверь (stdin, который предписывает SKILL.md) и
    мета-промпт по-прежнему срезали ведущий отступ первой строки, то есть
    маркер отступного блока кода, — и правка снова приходилась внутрь кода.

    Снимаем пустые строки в начале и пробелы в конце. Отступ первой
    содержательной строки — часть текста, а не мусор.
    """
    return re.sub(r"\A(?:[ \t]*\r?\n)+", "", text).rstrip()


#: Ширина отступа с раскрытием табов: таб тянет до следующей кратной четырём
#: колонки (CommonMark 2.2). Регулярка этого не умела и требовала непробельный
#: символ сразу после ОДНОГО таба, поэтому «\t\tКОД» и « \t КОД» считались
#: прозой и правились внутри — хотя по стандарту это отступный код.
def _ширина_отступа(строка):
    ширина = 0
    for символ in строка:
        if символ == " ":
            ширина += 1
        elif символ == "\t":
            ширина += 4 - (ширина % 4)
        else:
            break
    return ширина


def _это_отступный_код(строка):
    без_цитат = re.sub(r"\A(?:[ ]{0,3}>[ ]?)*", "", строка)
    if _ширина_отступа(без_цитат) < 4:
        return False
    остаток = без_цитат.lstrip(" \t")
    # Отступ перед МАРКЕРОМ пункта — это вложенный список, а не код.
    return bool(остаток) and not re.match(r"(?:[-*+]|\d{1,9}[.)])[ ]", остаток)


def _колонка(префикс):
    """Колонка рана внутри цитаты: маркеры `>` не считаются, остальное считается.

    Цитата — это уровень вложенности, он сверяется отдельно (по числу `>`), а
    маркер списка и пробелы задают колонку, от которой стандарт отмеряет
    закрывающему фенсу его три пробела.
    """
    return len(re.sub(r"[ ]{0,3}>[ ]?", "", префикс))


def _фенс_блоки(text):
    """[(начало, конец, закрыт)] для блоков кода — построчно, по CommonMark.

    Регулярка спаривает раны жадно и трёх правил стандарта не знает, а
    шестнадцатый круг показал, что каждое из них — живой промпт:

      закрывающий не короче открывающего   ````\nбыло: ```\n````  — блок ЗАКРЫТ,
                                           а спаривание врало «открыт»
      закрывающий без info string          ```python … ```js      — блок ОТКРЫТ,
                                           а спаривание считало ```js закрывающим
      отступ ≥ 4 пробелов — не фенс        ```\ncode\n    ```      — блок ОТКРЫТ

    Первые два дали по дефекту в противоположные стороны: инструмент замолчал
    там, где обязан был сработать, и вписал заметку в чужой код.
    """
    блоки = []
    поз = 0
    открыт = None                      # (символ, длина рана, база отступа, старт)
    html = None
    for строка in text.split("\n"):
        начало, конец = поз, поз + len(строка)
        поз = конец + 1
        s = строка.rstrip("\r")
        if html is not None:
            if "-->" in s:
                блоки.append((html, конец, True))
                html = None
            continue
        if открыт is not None:
            m = _ФЕНС_ЗАКР.match(s)
            if (m and m.group("ран")[0] == открыт[0]
                    and len(m.group("ран")) >= открыт[1]
                    and открыт[2][0] <= _колонка(m.group("pre")) <= открыт[2][1]
                    and m.group("pre").count(">") == открыт[4]):
                блоки.append((открыт[3], конец, True))
                открыт = None
            continue
        m = _ФЕНС_ОТКР.match(s)
        if m:
            ран = m.group("ран")
            # У бэктик-фенса info string не может содержать бэктик (CommonMark
            # 4.5) — иначе это инлайн-код, а не начало блока.
            if not (ран[0] == "`" and "`" in m.group("инфо")):
                # Нижняя граница отступа клозера — там, где начался ран. Вне
                # списка это ноль, и допуск получается абсолютный (CommonMark
                # даёт закрывающему фенсу не больше трёх пробелов); внутри
                # пункта — край его содержимого. Раньше нижней границы не было
                # вовсе, и « ```» закрывался четырёхпробельной строкой, которая
                # по стандарту уже содержимое, — нож с заметкой лезли в код.
                if m.group("список"):
                    # Внутри пункта отступ считается от края его содержимого.
                    # Выровнено ли тело пункта, без полного парсера контейнеров
                    # не узнать, поэтому выбираем в пользу молчания: клозер
                    # обязан стоять не левее опенера, иначе блок считается
                    # открытым и мы просто ничего не трогаем. Порча кода тут
                    # невозможна, цена — пропущенная находка на разметке,
                    # которую мы не разбираем.
                    рамка = (_колонка(m.group("pre")), _колонка(m.group("pre")) + 3)
                else:
                    # Вне списка допуск АБСОЛЮТНЫЙ: закрывающему фенсу стандарт
                    # даёт не больше трёх пробелов, независимо от отступа
                    # открывающего. Отсчёт от опенера пускал « ```» закрываться
                    # четырёхпробельной строкой, которая по стандарту уже
                    # содержимое, — и нож с заметкой лезли в код. Верхняя
                    # граница здесь дублирует `_ПРЕФИКС` (он и так не пропустит
                    # больше трёх пробелов) и оставлена ради явности: правило
                    # стандарта должно быть видно в коде, а не подразумеваться
                    # побочным свойством регулярки.
                    рамка = (0, 3)
                открыт = (ран[0], len(ран), рамка, начало, m.group("pre").count(">"))
                continue
        if _это_отступный_код(s) or _ЦИТАТА.match(s):
            # Цитата в промпте — почти всегда ЧУЖАЯ речь: письмо заказчика,
            # вывод команды, кусок тикета. Понижать в ней регистр и схлопывать
            # «!!!» значит править не свой текст — тот же класс, что и кавычки,
            # и решается так же: считаем данными.
            блоки.append((начало, конец, True))
            continue
        if _HTML_ОТКР.match(s):
            if "-->" in s:
                блоки.append((начало, конец, True))
            else:
                html = начало
    if открыт is not None:
        блоки.append((открыт[3], len(text), False))
    if html is not None:
        блоки.append((html, len(text), False))
    return блоки


def code_regions(text):
    """Все области кода в промпте: блоки-фенсы плюс инлайн-код и кавычки.

    ЕДИНСТВЕННЫЙ источник правды о границах кода на весь пакет. До
    семнадцатого круга их было два — жадная регулярка для маски/ножей и
    построчный сканер для гарда добавок, — и они расходились ровно там, где
    разметка нетривиальна. Каждое расхождение оказывалось дефектом.
    """
    блоки = _фенс_блоки(text)
    области = [(a, b) for a, b, _ in блоки]
    занято = [(a, b) for a, b in области]
    предыдущий = 0
    свободно = []
    for a, b in sorted(занято) + [(len(text), len(text))]:
        if a > предыдущий:
            край = предыдущий
            for m in CODE_SPAN.finditer(text, предыдущий, a):
                области.append((m.start(), m.end()))
                # Прямые кавычки считаем ТОЛЬКО в промежутках между уже
                # найденными спанами: кавычка внутри `код` не должна сбивать
                # чётность настоящих пар.
                свободно.append((край, m.start()))
                край = m.end()
            свободно.append((край, a))
        предыдущий = max(предыдущий, b)
    области.extend(_прямые_кавычки(text, свободно))
    return sorted(области)


def tail_inside_code(text):
    """Кончается ли промпт ВНУТРИ незакрытого блока кода.

    Если да, дописывать нечего и некуда: любая наша секция окажется внутри
    чужого кода. На промпте, который обрывался на ```python без закрывающего
    фенса, инструмент вклеивал в тело функции три плейсхолдера и «(Краткость:
    Ответь кратко.)» — исполнитель прочитал бы их как код. Находки при этом
    остаются: человеку показать надо, вписать в чужой блок — нельзя.

    Считаем по той же маске, что видят детекторы: `mask_code` сохраняет длину,
    поэтому достаточно сравнить последний непробельный символ.
    """
    if any(not закрыт for _, _, закрыт in _фенс_блоки(text)):
        return True
    # Фенс ПОСРЕДИ строки CommonMark блоком не считает, а промпт «допиши
    # ```python» человек оборвал на вставке кода — точка приклеилась бы к
    # info-string. Остаёмся консервативны ровно к этому случаю.
    последняя = text.rstrip().split("\n")[-1]
    if _ФЕНС_ОТКР.match(последняя) or _ФЕНС_ЗАКР.match(последняя):
        return False                   # строка-фенс: её уже посчитал сканер
    m = re.search(r"(?<=\S)[ \t]*(```|~~~)", последняя)
    return bool(m) and последняя.count(m.group(1)) < 2


#: Сколько текста ВНЕ блоков кода делает промпт «многочастным». Правило
#: вендора про XML-теги прямо оговаривает: «для одной короткой задачи не
#: нужно», — поэтому одного блока мало, вокруг него должна быть инструкция
#: длиной хотя бы в пару фраз.
_МИНИМУМ_ИНСТРУКЦИИ = 40


def _смешаны_текст_и_код(text):
    """Есть блок кода И заметная инструкция вокруг него."""
    блоки = [(a, b) for a, b, _ in _фенс_блоки(text)]
    if not блоки:
        return False
    вне, прошлый = [], 0
    for a, b in блоки:
        вне.append(text[прошлый:a])
        прошлый = max(прошлый, b)
    вне.append(text[прошлый:])
    return len("".join(вне).strip()) >= _МИНИМУМ_ИНСТРУКЦИИ


def analyze(prompt, target):
    """Вернуть список сработавших правил (findings) для данной модели.

    target: {family, generation}. Правила scope='family' проверяются всегда;
    scope=<generation-id> — только если target.generation совпадает.
    Правила с action='add'/check='always' не включаем в findings как «проблему»,
    их подхватывает rewrite/harness (кроме явных — они попадают в 'additions').
    """
    family = target.get("family")
    if not family:
        return []
    data = catalog.load_family(family)
    # Детекторам нужны не только family/generation, но и свойства семейства —
    # например имя контекстного файла (AGENTS.md / QWEN.md). Пробрасываем их
    # копией, чтобы не мутировать target вызывающей стороны.
    # `has_code_block` считаем по СЫРОМУ тексту: ниже он будет замаскирован, и
    # спросить «есть ли здесь блок кода» станет уже не у кого.
    target = dict(target, context_file=data.get("context_file"),
                  has_code_block=_смешаны_текст_и_код(prompt))
    prompt = mask_code(prompt)             # код — данные, а не инструкции
    low = prompt.lower()
    shape = None
    findings = []
    # поколение + те, чьи правила вендор объявил применимыми к нему (rules_of):
    # Mythos 5 ключуется на страницу Fable 5, Opus 4.7 — на guidance Opus 4.8
    scopes = catalog.scopes_for(family, target.get("generation"))
    for rule in data.get("rules", []):
        scope = rule.get("scope", "family")
        if scope != "family" and scope not in scopes:
            continue
        allowed_shapes = rule.get("when_shapes")
        if allowed_shapes:
            if shape is None:
                shape = task_shape(prompt)
            if shape not in allowed_shapes:
                continue
        check = rule.get("check", "always")
        fn = _CHECKS.get(check)
        if fn is None:
            continue
        if check == "always":
            # 'always'-правила — это добавления по умолчанию для поколения,
            # их показываем как рекомендации, но помечаем отдельно.
            # `skip_if_present` — «этого уже просили, второй раз не надо».
            # Без него `improve` не был идемпотентен: прогон улучшенного
            # промпта дописывал вторую «(Краткость: Ответь кратко.)», а
            # промпт, который сам кончался «Ответь кратко.», получал её же
            # третьей копией. Условие живёт в rules/*.json рядом с правилом,
            # а не в коде: где правило — там и его область неприменимости.
            уже = rule.get("skip_if_present")
            if уже and re.search(уже, low):
                continue
            findings.append(_as_finding(rule, always=True))
            continue
        if fn(prompt, low, target):
            findings.append(_as_finding(rule, always=False))
    return findings


def _as_finding(rule, always):
    return {
        "id": rule["id"],
        "title": rule["title"],
        "action": rule.get("action", "warn"),
        "why": rule.get("why", ""),
        "source": rule.get("source", ""),
        "check": rule.get("check", ""),
        "scope": rule.get("scope", "family"),
        "always": always,
    }


# ── форма задачи (для харнесса) ──────────────────────────────────────
_SHAPE_WORKFLOW = re.compile(
    r"(по всем файлам|во всех файлах|(все|всех|каждый|каждого)\s+файл\w*|по всему проекту|"
    r"across (all|every)|every file|codebase[- ]wide|весь проект целиком|тысяч\w* файл|"
    r"аудит безопасност|security audit|миграци\w* тысяч|(entire|whole) codebase)",
    re.I,
)
_SHAPE_LOOP = re.compile(
    r"(кажд(ый|ое|ую)\s+(день|утро|ночь|неделю|час)|ежедневн|ежечас|nightly|"
    r"по расписани|periodic|every (night|morning|day|hour|week)|раз в день|раз в час)",
    re.I,
)
_SHAPE_GOAL = re.compile(
    r"((пока|until|до тех пор)\b[^.\n]{0,60}"
    r"(пройд|прошл|проход|зелён|готов|заверш|compil|pass|hold|green|empty|исчез|пуст|clean|чист)"
    r"|до зелён|all tests pass|acceptance criteria|критери\w* приёмк|до готовн|backlog|"
    r"очередь задач|доведи до|доведи задачу)",
    re.I,
)
_SHAPE_PLANNING = re.compile(
    r"(как лучше|какой подход|с чего начать|спроектир|design (a|the)|архитектур|"
    r"architecture|отрефактор|\brefactor\b|не уверен|несколько файлов|multiple files|"
    r"how (should|do) (i|we)|продумай план|состав\w* план|нужно продумать)",
    re.I,
)
#: Признаки, которые сами по себе означают пустяк, что бы за ними ни стояло.
#: «Исправь опечатки: „превет“, „сонце“, „малако“» — три опечатки остаются тремя
#: опечатками, перечисление тут не спецификация, а список того же самого.
_TRIVIAL_STRONG = re.compile(
    r"(переименуй|опечат|\btypo\b|\brename\b|один символ)",
    re.I,
)
#: Признаки, которые пустяк лишь пока за ними ничего не расписано. «Подправь» —
#: слово-обманка: «подправь отступ» пустяк, «подправь расчёт комиссии: округляй
#: вверх до потолка 500» — правка денежной логики. Любое двоеточие после такого
#: слова означает, что дальше идут условия, а не уточнение.
#: «добавь лог» отсюда убрано совсем. Дословный вход из отчёта — «добавь
#: логирование с ротацией и маскированием PII» — пустяком не является, а
#: подпирать это порогом длины значит чинить под тест: строка в 49 символов
#: проходила, в 63 — нет, и от смысла это не зависело никак.
_TRIVIAL_WEAK = re.compile(r"(подправь|поправь мелк|измени строк)", re.I)


def task_shape(prompt):
    """Классифицировать задачу: workflow | loop | goal | planning | trivial | normal."""
    low = prompt.lower()
    if _SHAPE_WORKFLOW.search(low):
        return "workflow"
    if _SHAPE_LOOP.search(low):
        return "loop"
    if _SHAPE_GOAL.search(low):
        return "goal"
    if _SHAPE_PLANNING.search(low):
        return "planning"
    if len(prompt.strip()) <= 120:
        # Сильный признак решает сам: опечатка остаётся опечаткой, сколько бы их
        # ни перечислили. Слабый уступает любой спецификации после двоеточия —
        # прошлая редакция требовала ещё и запятую, и «подправь расчёт комиссии:
        # округляй вверх до потолка 500» проходило как пустяк.
        # Даже сильный признак уступает, если рядом стоит ВТОРОЕ дело со своим
        # предметом из кода: «переименуй колонку … и напиши миграцию» — это уже
        # не опечатка. Без этого пустяком считалась любая правка, начатая словом
        # «переименуй», сколько бы работы за ней ни следовало.
        if _TRIVIAL_STRONG.search(low) and not _CODE_NOUN.search(low):
            return "trivial"
        # Слабый признак уступает любой спецификации после двоеточия и длине:
        # «добавь логирование всех запросов с ротацией и маскированием PII» —
        # не лог-строка, а подсистема.
        if _TRIVIAL_WEAK.search(low) and not re.search(r"[:;]", prompt):
            return "trivial"
    # Раньше здесь стояло «короче 90 символов + глагол кода → trivial». Краткость и
    # пустяковость — разные вещи: «Напиши парсер JSON» умещается в 18 символов и
    # тривиальной задачей не является. Пока форма влияла только на совет по запуску,
    # ошибка была незаметна; как только по ней стали гейтиться правила, она начала
    # глушить законные требования к контексту и проверке. Признак тривиальности —
    # смысл задачи (опечатка, переименование, лог-строка), а не длина строки.
    return "normal"
