"""Детерминированный разбор промпта: какие правила семейства «срабатывают»
и какая у задачи форма (для рекомендации харнесса).

Ноль обращений к модели — только регэкспы/эвристики (RU+EN). Каждый детектор
привязан к правилу из rules/<family>.json по имени в поле "check".
"""

import re

from . import catalog

_CODING_VERB = re.compile(
    r"(напиш|добав|почин|исправ|сдела|реализ|перепиш|отрефактор|рефактор|создай|"
    r"удали|обнови|напис|оптимизир|ускор|внедри|вынеси|раздели|"
    r"implement|fix\b|add\b|write\b|refactor|create|build\b|"
    r"update\b|remove\b|migrat|тест|debug|отлад|optimi[sz]e)",
    re.I,
)
_PATH = re.compile(
    r"@|/|\b\w+\.(py|ts|tsx|js|jsx|go|rs|java|rb|php|json|md|html|css|scss|sql|yml|yaml|toml)\b"
    r"|\bsrc\b|\bкаталог|\bпапк|\bмодул",
    re.I,
)
_VERIFY_MEANS = re.compile(
    r"(тест|test|сборк|build|pytest|jest|npm |lint|прогони|run |скрин|screenshot|"
    r"exit code|assert|провер\w* (что|сборк|прошл)|passes|компилир)",
    re.I,
)


#: Предмет задачи по коду. Без него глагол ничего не значит: «напиши» одинаково
#: начинает «напиши функцию валидации» и «напиши разбор конкурента», а требовать
#: у второго файл через @ и прогон тестов — бессмыслица.
#:
#: Границы слова здесь не украшение. Первая редакция поставила их только там, где
#: я заметил проблему («апи» внутри «напиши»), и остальные корни остались голыми:
#: «тест» находился внутри «аттестации», «метод» внутри «методику», «класс» внутри
#: «классический», «script» внутри «description» — и любая просьба написать
#: положение, методику или лендинг разбиралась как задача по коду.
#:
#: Поэтому корни разделены. Коротким мало левой границы: им нужен ещё контроль
#: окончания — только обычное падежное и сразу конец слова. Длинные однозначны.
#: Весь список целиком проверяется тестом по словарю, а не на одном примере.
#: Падежные окончания, включая согласные: без них терялись «тестов», «багом»,
#: «методов», «классах», «модулях» — то есть большинство живых форм.
_RU_ENDING = r"(?:ами|ями|ах|ях|ов|ев|ом|ем|ам|ям|ой|ей|ы|и|а|я|у|ю|е|о|ь)?\b"
#: «тесто» отсекаем отдельно: съедобное к коду отношения не имеет.
_CODE_NOUN_STRICT = ("функци", "метод", "класс", "модул", "скрипт", "тест(?!о\\b|остерон)", "схем",
                     "баг", "ветк", "апи", "сборк", "билд")
#: Длинные корни однозначны: слова, которые с них начинаются, и так про код.
_CODE_NOUN_LOOSE = ("эндпоинт", "роут", "компонент", "миграци", "репозитор", "коммит",
                    "парсер", "валидац", "хендлер", "конфиг", "деплой", "ошибк")
#: Английские формы задаются ЯВНО, а не корнем с общим суффиксом. Общий суффикс
#: `(s|es|ing)?` впустил обратно «building» (через build+ing) и «testes» (test+es),
#: а «queries» не поймал вовсе — query+s такой формы не даёт. Перечислить формы
#: руками дешевле, чем ловить каждое исключение.
_CODE_NOUN_EN = (
    r"endpoints?", r"routes?", r"handlers?", r"configs?", r"quer(?:y|ies)",
    r"functions?", r"methods?", r"class(?:es)?", r"modules?", r"scripts?",
    r"components?", r"migrations?", r"parsers?", r"apis?", r"bugs?",
    r"tests?", r"testing", r"builds?",
)
#: «Запрос» намеренно НЕ в списке: в русском это чаще запрос в суд, чем к базе.
_CODE_NOUN = re.compile(
    r"\b(?:"
    + "|".join(r + _RU_ENDING for r in _CODE_NOUN_STRICT)
    + "|"
    + "|".join(_CODE_NOUN_LOOSE)
    + "|"
    + "|".join(r + r"\b" for r in _CODE_NOUN_EN)
    + r")",
    re.I,
)


def _coding_task(low, prompt=None):
    if not _CODING_VERB.search(low):
        return False
    # Путь или @-ссылка сами по себе доказывают, что речь про код.
    if prompt is not None and _PATH.search(prompt):
        return True
    return bool(_CODE_NOUN.search(low))


