#: Задача, у которой нет и не может быть файла: разведка, обзор, сравнение, текст.
#: Требовать у такой «сошлитесь на файл через @» бессмысленно — ссылаться не на что.
_RESEARCH_TASK = re.compile(
    r"(обзор|исследован|разведк|сравни|проанализируй рынок|подбер\w* источник|"
    r"найди в интернете|погугли|research|market (overview|research)|competitive|"
    r"собери информаци|что известно о|сделай выжимк|конспект|дайджест)",
    re.I,
)
#: Явно расписанный формат ответа: нумерованный или маркированный список пунктов,
#: которым автор уже задал структуру выдачи. Слов «формат» и «в виде» в нём может
#: не быть ни одного, но контракт на результат тут есть.
_EXPLICIT_LAYOUT = re.compile(r"(?m)^\s*(\d+[.)]\s+\S|[-*•]\s+\S)")


#: Маркер, после которого задача — точно разведка, чем бы её предмет ни был:
#: «обзор рынка API-шлюзов» остаётся обзором рынка, а не задачей по коду.
#: Голое «конкурент\\w*» отсюда убрано: в русском «конкурентный доступ» — это про
#: параллелизм, и «исправь баг конкурентного доступа» глушилось как рыночный обзор.
_RESEARCH_STRONG = re.compile(
    r"(обзор рынка|анализ рынка|сравни\w* цен\w*\s+(?:на|для|у)\b|сравни\w* тариф|"
    r"конкурентов|конкурентами|(?:обзор|анализ|сравнение)\s+конкурент|"
    r"market (overview|research)|competitive analysis|подбер\w* источник|дайджест)",
    re.I,
)
#: Глагол, который МЕНЯЕТ код. Его присутствие означает: чем бы задача ни казалась
#: по маркерам, работать придётся с файлами, и требования к контексту и проверке
#: нужны. Это надёжнее любого перечня существительных: «сделай обзор» ничего не
#: меняет, «исправь баг конкурентного доступа» меняет — и неважно, какие слова
#: стоят рядом.
_MUTATING_VERB = re.compile(
    r"(почин|исправ|отрефактор|рефактор|оптимизир|ускор|добав|удали|перепиш|"
    r"реализ|внедри|обнови|мигрир|напиш|создай|сдела|сгенер|вынеси|раздели|"
    r"\bfix\b|refactor|implement|optimi[sz]e|migrate|\bwrite\b|create|\bbuild\b)",
    re.I,
)


def _has_code_action(low):
    """Есть ли в тексте «меняющий глагол + его предмет из кода».

    Одного глагола мало, и одного существительного мало — важно, к ЧЕМУ глагол
    относится. Сравните:

        «сделай обзор рынка API-шлюзов»   — «api» это ПРЕДМЕТ ОБЗОРА, не работы
        «создай скрипт сбора цен»          — «скрипт» это то, что делают

    Отличаем по тому, что стоит МЕЖДУ глаголом и существительным: если там слово
    разведки («обзор», «анализ рынка»), значит существительное принадлежит ей, а
    не глаголу. Обе прошлые редакции спотыкались именно здесь: сначала сильный
    маркер глушил кодовые задачи, потом глагол с существительным где угодно в
    тексте забирал себе рыночный обзор.
    """
    for m in _MUTATING_VERB.finditer(low):
        noun = _CODE_NOUN.search(low, m.end())
        if not noun:
            continue
        between = low[m.end():noun.start()]
        if _RESEARCH_TASK.search(between) or _RESEARCH_STRONG.search(between):
            continue                       # существительное принадлежит разведке
        return True
    return False


def _is_research(low, prompt=None):
    """Разведка — только пока задача ничего не меняет в коде.

    «Проведи исследование бага в парсере и исправь причину» тоже содержит слово
    «исследование», но это кодовая задача, и глушить у неё требования к контексту
    и проверке нельзя. Ложноотрицательное здесь опаснее ложноположительного:
    несработавшее правило человек не видит вообще.
    """
    if not _RESEARCH_TASK.search(low):
        return False
    # Меняющий глагол перебивает любой маркер разведки, включая сильный. Прошлая
    # редакция ставила сильный маркер первым, и «исправь баг конкурентного доступа
    # и сравни результаты» оставалось совсем без правил.
    if _has_code_action(low):
        return False
    if _RESEARCH_STRONG.search(low):
        return True                        # предмет не важен: это точно разведка
    if _CODE_NOUN.search(low):
        return False
    if prompt is not None and _PATH.search(prompt):
        return False
    return True


def _c_missing_context(p, low, t):
    # Мелкой правке контекст-секция не нужна: «исправь опечатку» и так однозначно,
    # а требование «заскоупить задачу» на ней выглядит бюрократией. И у разведки
    # без единого файла требовать @-ссылку не на что.
    if task_shape(p) == "trivial" or _is_research(low, p):
        return False
    return _coding_task(low, p) and not _PATH.search(p)


def _c_missing_verification(p, low, t):
    # То же для проверки: на однострочной правке прогон тестов — оверхед, а не
    # дисциплина. Форма задачи здесь решает раньше ключевых слов.
    if task_shape(p) == "trivial" or _is_research(low, p):
        return False
    return _coding_task(low, p) and not _VERIFY_MEANS.search(low)


