#: Навязанная модели ЦЕПОЧКА РАССУЖДЕНИЙ. Ровно то же определение, что у ножа в
#: `rewrite._COT` — иначе отчёт находит больше, чем переписчик умеет починить.
#: Прошлая редакция ловила голые «пошагово» и «по шагам» и печатала «[-] Убрать»
#: на «Опиши пошагово процесс деплоя», хотя нож эту фразу уже (правильно) не трогал.
#: Ровно те же формы, что режет нож. Голые `step-by-step` и `chain of thought`
#: отсюда убраны: нож их не трогает (и правильно — это про формат ответа), а
#: детектор печатал «[-] Убрать», обещая правку, которой не будет. Совпадение
#: детектора и ножа проверяется тестом, а не комментарием: комментарий про «ровно
#: то же определение» тут уже стоял и был неправдой.
_FORCED_COT = re.compile(
    r"(?i)(?:(?:думай|рассуждай|размышляй|подумай)\s+(?:пошагово|шаг за шагом|по шагам)|"
    r"think step by step|let'?s think(?: step by step)?|рассуждай вслух)"
)
#: Просьба ПОКАЗАТЬ рассуждение — другой смысл и другое правило. Для Fable 5 это
#: триггер отказа (reasoning_extraction), а «думай пошагово» — нет: там просят
#: думать, а не предъявлять ход мысли.
_SHOW_THINKING = re.compile(
    r"(?i)(?:покажи ход мыслей|распиши (?:свои )?рассуждени\w*|"
    r"воспроизведи рассуждени\w*|show (?:me )?your (?:reasoning|thinking|thoughts))"
)


#: Зависимый хвост после фразы: «распиши рассуждения О рисках миграции». Такую
#: фразу нож не режет — дополнение осталось бы без своего глагола. Значит и
#: детектор не должен по ней срабатывать: иначе отчёт обещает правку, которой не
#: будет. Один гард на обоих; живёт здесь, а импортируется в `rewrite`.
DEPENDENT_TAIL = re.compile(r"\s*(?:о|об|обо|про|about|on|when|при)\b", re.I)


def _cuttable(p, pattern):
    """Есть ли в тексте хотя бы одно вхождение, которое можно безопасно вырезать."""
    return any(not DEPENDENT_TAIL.match(p, m.end()) for m in pattern.finditer(p))


def _c_forced_cot(p, low, t):
    return _cuttable(p, _FORCED_COT)


def _c_show_thinking(p, low, t):
    return _cuttable(p, _SHOW_THINKING)


def _c_repetition(p, low, t):
    sents = [s.strip() for s in re.split(r"[.!?\n]+", low) if len(s.strip()) > 12]
    seen = {}
    for s in sents:
        seen[s] = seen.get(s, 0) + 1
        if seen[s] >= 2:
            return True
    for key in ("обязательно", "сначала спроси", "не забудь", "напоминаю"):
        if low.count(key) >= 2:
            return True
    return False


def _c_contradiction_hint(p, low, t):
    pairs = [
        ("кратко", "подробно"),
        ("кратко", "детальн"),
        ("коротко", "развернут"),
        ("markdown", "без форматирован"),
        ("без форматирован", "в формате"),
        ("быстро", "тщательно"),
        ("brief", "detailed"),
    ]
    return any(a in low and b in low for a, b in pairs)


def _c_needs_agents_md(p, low, t):
    """Постоянные правила проекта просятся в контекстный файл, а не в промпт.

    Раньше проверка была прибита к семейству `openai` и его AGENTS.md. Но такой
    файл есть у каждого агентного CLI, просто называется по-разному: AGENTS.md
    у Codex и Kimi, QWEN.md у Qwen Code. Имя берём из семейства (`context_file`),
    а не зашиваем — иначе каждый новый вендор требует правки кода.
    """
    if not t.get("context_file"):
        return False
    return bool(
        re.search(
            r"(всегда|каждый раз|во всех задачах|в целом по проекту|стиль кода|"
            r"code style|always use|every time|по всему проекту)",
            low,
        )
    )


