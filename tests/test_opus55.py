# -*- coding: utf-8 -*-
"""Claude Opus 5.5: поколение, его правила и детектор фронтенд-задач.

Вышла 22 сентября 2026. Вендор прямо пишет, что промпты для Opus 5 работают и
здесь, поэтому правила Opus 5 наследуются через `rules_of`, а сверху ложатся
различия 5.5 — те, что видны прямо в тексте промпта: новая категория отказа
`reasoning_extraction`, привычка заканчивать ход отчётом вместо вызова
инструмента, бесполезное теперь «думай пошагово», разведка в связке приложений
и дизайнерские дефолты во фронтенде.

Остальные различия 5.5 к тексту промпта не относятся (мышление не выключается,
дефолт effort — medium, принудительный вызов инструмента не поддерживается) и
живут в `note` поколения, а не в правилах.
"""

import json
import os

import pytest

from nativeprompt.analyze import analyze
from nativeprompt.catalog import scopes_for
from nativeprompt.detect import resolve
from nativeprompt.explain import build_report
from nativeprompt.rewrite import rewrite

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПРАВИЛА = json.load(open(os.path.join(КОРЕНЬ, "nativeprompt", "rules", "claude.json"),
                         encoding="utf-8"))


def ids(промпт, модель="claude-opus-5-5"):
    return {f["id"] for f in analyze(промпт, resolve(модель))}


# ── поколение ───────────────────────────────────────────────────────────
@pytest.mark.parametrize("что_ввели", [
    "claude-opus-5-5", "opus-5-5", "opus-5.5", "opus55", "Claude Opus 5.5",
    "anthropic/claude-opus-5-5",
])
def test_поколение_опознаётся(что_ввели):
    """Человек пишет модель как придётся: из каталога, из конфига, на слух."""
    t = resolve(что_ввели)
    assert t["family"] == "claude", "%s ушло не в claude: %s" % (что_ввели, t)
    assert t["generation"] == "opus-5-5", (
        "%s не опознано как opus-5-5, получили %r" % (что_ввели, t.get("generation")))


def test_пятьпять_не_проваливается_в_opus_5():
    """Токен «opus-5» — подстрока «claude-opus-5-5».

    Порядок поколений в файле и есть единственная защита: `generation_for`
    возвращает первое совпадение. Стоило бы opus-5 оказаться выше — вся
    линейка 5.5 молча читалась бы как Opus 5, и человек не заметил бы.
    """
    ключи = list(ПРАВИЛА["generations"])
    assert ключи.index("opus-5-5") < ключи.index("opus-5"), (
        "opus-5 стоит выше opus-5-5 — 5.5 будет опознаваться как 5: %s" % ключи)


def test_у_поколения_есть_ссылка_на_свой_гайд():
    g = ПРАВИЛА["generations"]["opus-5-5"]
    assert g["doc"].startswith("https://platform.claude.com/"), g
    assert "prompting-claude-opus-5-5" in g["doc"], (
        "ссылка ведёт не на страницу 5.5: %s" % g["doc"])


def test_правила_opus_5_наследуются():
    """Вендор пишет: страница Opus 5 остаётся разумной отправной точкой.

    Это не наша догадка про похожесть моделей, а прямое указание в доке —
    и оно выражается полем `rules_of`, а не копией правил.
    """
    assert ПРАВИЛА["generations"]["opus-5-5"]["rules_of"] == "opus-5"
    assert {"opus-5-5", "opus-5"} <= scopes_for("claude", "opus-5-5")
    assert "opus5-report-all" in ids("покажи только критичные замечания")


def test_поколение_называет_ломающие_изменения_рантайма():
    """Они не лечатся текстом промпта, поэтому правилами не стали.

    Но промолчать о них нельзя: человек, который перенёс код с Opus 5, получит
    400 на первом же запросе. Место для такого — `note` поколения.
    """
    note = ПРАВИЛА["generations"]["opus-5-5"]["note"].lower()
    for что in ("мышление", "effort", "инструмент"):
        assert что in note, "в note поколения не сказано про %s: %s" % (что, note)


# ── правила поколения ───────────────────────────────────────────────────
ПРАВИЛА_55 = [r for r in ПРАВИЛА["rules"] if r.get("scope") == "opus-5-5"]


def test_правила_заведены():
    assert len(ПРАВИЛА_55) >= 4, "правил под 5.5 почти нет: %s" % [
        r["id"] for r in ПРАВИЛА_55]


def test_у_каждого_правила_якорь_на_раздел():
    """Страница 5.5 длинная и разделена якорями.

    Ссылка на неё целиком заставляет искать нужный абзац глазами — ровно то,
    от чего правило и должно избавлять.
    """
    for r in ПРАВИЛА_55:
        assert "#" in r["source"], "%s: ссылка без якоря: %s" % (r["id"], r["source"])
        assert "prompting-claude-opus-5-5" in r["source"], (
            "%s: ссылка ведёт не на страницу 5.5: %s" % (r["id"], r["source"]))


def test_отказ_за_показ_рассуждений_горит_на_5_и_на_55():
    """Сначала reasoning_extraction была новой именно в 5.5, и правило жило
    только там. В ноябре 2026 страница Opus 5 получила раздел «Reasoning in the
    response» с той же категорией: правило переехало на Opus 5, а 5.5 его
    наследует через rules_of. Отдельного правила 5.5 больше нет, чтобы одна
    и та же находка не печаталась дважды.
    """
    промпт = "разбери этот лог и покажи ход мыслей"
    assert "opus5-no-show-thinking" in ids(промпт)
    assert "opus5-no-show-thinking" in ids(промпт, "claude-opus-5")
    assert "opus55-no-show-thinking" not in ids(промпт)


def test_правило_про_отказ_называет_категорию():
    """Без имени категории совет нечем проверить в своих логах."""
    r = next(r for r in ПРАВИЛА["rules"] if r["id"] == "opus5-no-show-thinking")
    assert "reasoning_extraction" in r["why"], r["why"][:200]
    assert "refusal" in r["why"], r["why"][:200]


def test_конец_хода_горит_на_длинной_задаче_и_молчит_на_короткой():
    длинная = ("прогони миграцию всех эндпоинтов на новый клиент, обнови тесты "
               "и собери отчёт по каждому шагу")
    короткая = "переименуй колонку created в created_at"
    assert "opus55-finish-unattended" in ids(длинная)
    assert "opus55-finish-unattended" not in ids(короткая)


def test_думай_пошагово_помечается():
    assert "opus55-drop-think-carefully" in ids("думай пошагово и реши задачу")
    assert "opus55-drop-think-carefully" not in ids("реши задачу")


def test_разведка_только_на_связке_приложений():
    """`when_shapes` у правила — workflow. На обычной правке разведка не нужна."""
    r = next(r for r in ПРАВИЛА_55 if r["id"] == "opus55-explore-multi-app")
    assert r["when_shapes"] == ["workflow"]
    assert "opus55-explore-multi-app" not in ids("почини баг в @src/auth.py")


# ── детектор фронтенд-задач ─────────────────────────────────────────────
@pytest.mark.parametrize("промпт", [
    "сделай лендинг для студии на React",
    "собери дашборд с метриками на Tailwind",
    "сверстай страницу тарифов, html и css",
    "build a landing page for the launch",
])
def test_фронтенд_задача_опознаётся(промпт):
    assert "opus55-frontend-antipatterns" in ids(промпт), (
        "не опознано как фронтенд: %r" % промпт)


@pytest.mark.parametrize("промпт", [
    "почини миграцию в @src/users_repo.py",
    "почему на мобиле съезжает css",          # предмет есть, просьбы сделать нет
    "поправь отступ у кнопки",                # ни предмета, ни создания
    "спроектируй дизайн схемы базы под заказы",  # «дизайн» есть, фронтенда нет
])
def test_не_фронтенд_не_считается_фронтендом(промпт):
    assert "opus55-frontend-antipatterns" not in ids(промпт), (
        "задача принята за фронтенд: %r" % промпт)


def test_правило_про_дизайн_перечисляет_приёмы_а_не_общий_запрет():
    """Вендор прямо пишет: общий запрет меняет один дефолт на другой.

    Значит ценность правила — в поимённом списке. Потеряется список —
    останется то самое «избегай ИИ-шного вида», от которого толку нет.
    """
    r = next(r for r in ПРАВИЛА_55 if r["id"] == "opus55-frontend-antipatterns")
    низ = r["why"].lower()
    assert "01/02/03" in низ, "потерян пример с нумерацией разделов: %s" % r["why"][:200]
    for приём in ("фон", "курсив", "моноширин", "таблетк"):
        assert приём in низ, "в списке нет приёма %r: %s" % (приём, r["why"][:200])


# ── переписчик ──────────────────────────────────────────────────────────
def test_добавления_доезжают_до_переписанного_промпта():
    """`add` обязан что-то дописать, иначе правило обещает правку, которой нет."""
    промпт = ("прогони миграцию всех эндпоинтов на новый клиент, обнови тесты "
              "и собери отчёт по каждому шагу")
    t = resolve("claude-opus-5-5")
    находки = analyze(промпт, t)
    r = rewrite(промпт, t, находки)
    assert "opus55-finish-unattended" in r["applied"], r["applied"]
    assert "Конец хода" in r["improved"], r["improved"][:400]


def test_совет_по_дизайну_идёт_плейсхолдером_а_не_готовым_списком():
    """Перечень запрещённых приёмов зависит от проекта.

    Подставить вендорский пример как решение автора значило бы выбрать за него
    стиль. Вендорский список остаётся подсказкой внутри плейсхолдера.
    """
    промпт = "сделай лендинг для студии на React"
    t = resolve("claude-opus-5-5")
    r = rewrite(промпт, t, analyze(промпт, t))
    assert "opus55-frontend-antipatterns" in r["applied"], r["applied"]
    assert "‹" in r["improved"], r["improved"][:400]


# ── отчёт целиком ───────────────────────────────────────────────────────
def test_отчёт_собирается_и_называет_поколение():
    r = build_report("сделай лендинг для студии на React", "claude-opus-5-5")
    assert r["meta"]["generation"] == "opus-5-5"
    assert r["improved"], "пустой результат"


def test_версия_правил_claude_поднята_под_55():
    """Шпаргалка датируется днём сверки с доками, иначе непонятно, что в ней учтено."""
    assert ПРАВИЛА["rules_version"] >= "2026-09-23", (
        "rules_version не обновлён: %s" % ПРАВИЛА["rules_version"])
