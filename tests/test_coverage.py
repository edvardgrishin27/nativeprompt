"""Команда `coverage`: сколько правил вендора закрывается на ваших промптах.

Величина, которую инструмент имеет право публиковать. Она НЕ про качество
ответа модели — модель не запускается вовсе, — а про соответствие официальным
рекомендациям: сколько их нарушал промпт, сколько закрыл инструмент, сколько
оставил вам и сколько внёс сам. Последнее обязано быть нулём.

Проверять качество ответа офлайн нельзя честно: для этого нужен и датасет,
и запуск модели, и второй запуск для сравнения. Проверять покрытие правил —
можно, и результат воспроизводим побайтово, потому что внутри нет ни модели,
ни сети.
"""

import io
import json
import os
import subprocess
import sys

import pytest

from test_invariant import КОРПУС

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
МОДЕЛИ = "claude-opus-5,gpt-5.6-sol,claude-fable-5"


def _прогнать(путь, *ещё):
    return subprocess.run(
        [sys.executable, "-m", "nativeprompt", "coverage", путь] + list(ещё),
        capture_output=True, text=True, cwd=КОРЕНЬ,
    )


@pytest.fixture
def корпус_текстом(tmp_path):
    блоки = [(э[0] if isinstance(э, tuple) else э) for э in КОРПУС]
    p = tmp_path / "korpus.txt"
    p.write_text("\n\n".join(б for б in блоки if б.strip()), encoding="utf-8")
    return str(p)


@pytest.fixture
def корпус_json(tmp_path):
    блоки = [(э[0] if isinstance(э, tuple) else э) for э in КОРПУС]
    p = tmp_path / "korpus.json"
    p.write_text(json.dumps(блоки, ensure_ascii=False), encoding="utf-8")
    return str(p)


def test_на_корпусе_инструмент_не_вносит_ни_одной_находки(корпус_json):
    """Главное свойство: корзина «внесено» пуста, иначе счёт не имеет смысла.

    Это то же утверждение, что и в test_verify, но через настоящий CLI:
    пользователь получает цифру именно оттуда, а не из функции.
    """
    r = _прогнать(корпус_json, "--models", МОДЕЛИ, "--json")
    assert r.returncode == 0, r.stderr
    d = json.loads(r.stdout)
    assert d["introduced"] == 0, "инструмент внёс находки сам: %s" % d


def test_счёт_сходится_сам_с_собой(корпус_json):
    """Закрыто плюс оставлено обязано равняться общему числу находок.

    Дешёвая проверка, которая ловит целый класс ошибок в подсчёте: потерянную
    корзину, двойной учёт, отфильтрованный по дороге отчёт.
    """
    d = json.loads(_прогнать(корпус_json, "--models", МОДЕЛИ, "--json").stdout)
    assert d["closed"] + d["left"] == d["findings"]
    assert d["runs"] == d["prompts"] * d["models"]
    assert sum(d["closed_by_rule"].values()) == d["closed"]


def test_цифра_воспроизводима_между_прогонами(корпус_json):
    """Внутри нет ни модели, ни сети — значит два прогона обязаны совпасть.

    Если эта проверка когда-нибудь покраснеет, значит в счёт пролезла
    недетерминированность, и публиковать такое число уже нельзя.
    """
    первый = _прогнать(корпус_json, "--models", МОДЕЛИ, "--json").stdout
    второй = _прогнать(корпус_json, "--models", МОДЕЛИ, "--json").stdout
    assert первый == второй


def test_оба_формата_дают_один_счёт(корпус_текстом, корпус_json):
    """JSON-массив и текст с пустой строкой — разные входы, счёт один.

    Формат влияет только на то, как файл разбирается на промпты; всё, что
    считается дальше, от него зависеть не должно.
    """
    т = json.loads(_прогнать(корпус_текстом, "--models", МОДЕЛИ, "--json").stdout)
    ж = json.loads(_прогнать(корпус_json, "--models", МОДЕЛИ, "--json").stdout)
    assert т["findings"] == ж["findings"]
    assert т["closed"] == ж["closed"]


def test_пустой_промпт_не_попадает_в_счёт(tmp_path):
    """В корпусе есть пустой промпт — граничный случай для других тестов.

    Считать по нему покрытие бессмысленно: находок там не будет никогда,
    и он занизил бы долю закрытых, ничего не проверив.
    """
    p = tmp_path / "с_пустым.json"
    p.write_text(json.dumps(["", "  ", "Почини баг в @src/a.py"], ensure_ascii=False), encoding="utf-8")
    d = json.loads(_прогнать(str(p), "--model", "claude-opus-5", "--json").stdout)
    assert d["prompts"] == 1


def test_вывод_не_обещает_качества(корпус_json):
    """Ни слова «лучше», ни процента улучшения — только счёт правил.

    Ровно та граница, за которую проект не заходит: инструмент применяет
    правила вендора и не утверждает, что ответ модели стал лучше.
    """
    вывод = _прогнать(корпус_json, "--models", МОДЕЛИ).stdout.lower()
    # Ищем именно ОБЕЩАНИЯ. Слово «качество» в самом отказе («это не оценка
    # качества ответа») — правильное употребление, и запрещать его нельзя:
    # тогда тест начнёт требовать убрать честную оговорку.
    for оборот in ("стало лучше", "на % лучше", "улучшил", "прирост",
                   "качество выросло", "эффективнее"):
        assert оборот not in вывод, "вывод обещает %r" % оборот
    assert "модель не запускалась" in вывод


def test_битый_json_не_роняет_команду(tmp_path):
    """Файл, похожий на JSON, но сломанный: внятная ошибка, а не трейсбек."""
    p = tmp_path / "битый.json"
    p.write_text('["незакрытая строка', encoding="utf-8")
    r = _прогнать(str(p), "--model", "claude-opus-5")
    assert r.returncode == 2
    assert "не разбирается" in r.stderr


def test_несуществующий_файл_не_роняет_команду(tmp_path):
    r = _прогнать(str(tmp_path / "нет.txt"), "--model", "claude-opus-5")
    assert r.returncode == 2
    assert "Не смог прочитать" in r.stderr


def test_неопознанная_модель_не_считается_молча(корпус_json):
    """Иначе пустой счёт прочитался бы как «нарушений нет»."""
    r = _прогнать(корпус_json, "--model", "нетакоймодели")
    assert r.returncode == 1
    assert "не опознана" in r.stderr


def test_опубликованная_цифра_не_устарела(корпус_json):
    """Сторож на само число из README: 38 процентов закрытых.

    Тот же класс защиты, что и у остальных опубликованных цифр: поменяется
    правило или корпус — покраснеет здесь, а не у читателя.
    """
    d = json.loads(_прогнать(корпус_json, "--models", МОДЕЛИ, "--json").stdout)
    доля = round(100.0 * d["closed"] / d["findings"])
    for имя in ("README.md", "README.ru.md", "CLAIMS.md", "CLAIMS.ru.md"):
        текст = io.open(os.path.join(КОРЕНЬ, имя), encoding="utf-8").read()
        if "coverage" not in текст:
            continue
        assert str(доля) in текст, (
            "%s не содержит актуальной доли закрытых (%d%%)" % (имя, доля))
