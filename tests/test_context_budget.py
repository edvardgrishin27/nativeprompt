# 1. Гарантия: потолок соблюдён
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_контекст_всегда_в_пределах_потолка(промпт, причина, модель):
    отчёт = build_report(промпт, модель)
    текст = хук.build_context(отчёт)
    assert len(текст) <= хук.ПОТОЛОК_КОНТЕКСТА, (
        "%s | %s: %d символов при потолке %d"
        % (причина, модель, len(текст), хук.ПОТОЛОК_КОНТЕКСТА))


def test_синтетический_вход_средней_ступени_тоже_в_пределах():
    """Ступень 2 корпус не задевает — проверяем её отдельным входом."""
    for модель in МОДЕЛИ:
        отчёт = build_report(ПРОМПТ_СРЕДНЕЙ_СТУПЕНИ, модель)
        текст = хук.build_context(отчёт)
        assert len(текст) <= хук.ПОТОЛОК_КОНТЕКСТА, (модель, len(текст))


def test_потолок_действительно_режет():
    """Мутационная страховка: потолок обязан быть НИЖЕ неурезанного худшего.

    Поставьте потолок выше — этот тест краснеет, и правильно: потолок, который
    никогда не срабатывает, ничего не гарантирует, он комментарий.
    """
    без_урезания = max(len(хук._собрать(о, 0)) for _, о, _ in _контексты())
    assert без_урезания > хук.ПОТОЛОК_КОНТЕКСТА, (
        "неурезанный худший случай %d уже помещается в потолок %d — "
        "потолок ничего не сторожит" % (без_урезания, хук.ПОТОЛОК_КОНТЕКСТА))


def test_опубликованный_худший_случай_не_устарел():
    """Сторожим само ЧИСЛО, а не только потолок.

    Потолок может соблюдаться, а опубликованная цифра — разъехаться с кодом.
    Здесь замер делает тест, а документация обязана совпасть с ним посимвольно.
    """
    замер = max(len(т) for т, _, _ in _контексты())
    assert замер == ХУДШИЙ_СЛУЧАЙ, (
        "худший случай стал %d вместо %d — обновите ХУДШИЙ_СЛУЧАЙ и обе CLAIMS"
        % (замер, ХУДШИЙ_СЛУЧАЙ))
    # Шаблон нарочно узкий: слово «худший случай» в тексте встречается дважды —
    # рядом с НЕурезанным замером (3528) и рядом с итоговым. Широкий шаблон
    # поймал бы первое число и краснел на верной документации.
    for имя, шаблон in (
        ("CLAIMS.ru.md", r"худший случай после урезания[^\n]*?(\d+) символ"),
        ("CLAIMS.md", r"worst case after trimming[^\n]*?(\d+) character"),
    ):
        текст = io.open(_КОРЕНЬ / имя, encoding="utf-8").read()
        m = re.search(шаблон, текст)
        assert m, "пропала строчка про худший случай в %s" % имя
        assert int(m.group(1)) == замер, (
            "%s обещает %s символов, замер даёт %d" % (имя, m.group(1), замер))


def test_потолок_назван_в_документации():
    """Потолок — обещание пользователю, а не внутренняя константа."""
    for имя in ("CLAIMS.ru.md", "CLAIMS.md", "README.ru.md", "README.md"):
        текст = io.open(_КОРЕНЬ / имя, encoding="utf-8").read()
        assert re.search(r"\b%d\b" % хук.ПОТОЛОК_КОНТЕКСТА, текст), (
            "%s не называет потолок %d" % (имя, хук.ПОТОЛОК_КОНТЕКСТА))


# ═══════════════════════════════════════════════════════════════════════
# 2. Текст пользователя цел или отсутствует — никогда не обрезан
# ═══════════════════════════════════════════════════════════════════════
def _длинные_строки(текст):
    """Строки, по которым можно опознать утечку куска текста пользователя.

    Короткие не годятся: «```» и одиночные слова встречаются и в наших блоках.
    """
    return [с for с in текст.splitlines() if len(с.strip()) > 20]


@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_текст_пользователя_или_цел_или_его_нет(промпт, причина, модель):
    """Половина промпта — это не короткий промпт, а ДРУГОЙ промпт.

    Обрезанный по бюджету текст модель прочитает как законченное поручение и
    пойдёт делать не ту задачу; это дороже, чем не показать текст вовсе.
    Поэтому блок либо стоит целиком, либо не стоит — и второе проверяется
    строже первого: ни одной длинной строки улучшенной версии не должно
    просочиться мимо блока.
    """
    отчёт = build_report(промпт, модель)
    текст = хук.build_context(отчёт)
    if not текст:
        return
    метка = "%s | %s" % (причина, модель)
    if "Улучшенная версия промпта:" in текст:
        assert отчёт["improved"] in текст, "блок есть, а текст урезан: " + метка
        return
    for строка in _длинные_строки(отчёт["improved"]):
        assert строка not in текст, "утёк кусок текста пользователя: %s\n%r" % (метка, строка)


def test_на_длинном_промпте_блок_снимается_а_не_режется():
    """Пин на самый длинный промпт корпуса — тот, ради которого всё это.

    Промпт берём из корпуса вычислением, а не копией строк: копия разойдётся с
    корпусом при первой же его правке.
    """
    промпт = max(КОРПУС, key=lambda пара: len(пара[0]))[0]
    отчёт = build_report(промпт, "claude-opus-5")
    текст = хук.build_context(отчёт)
    assert len(текст) <= хук.ПОТОЛОК_КОНТЕКСТА, len(текст)
    assert "урезан" in текст, текст[:200]
    assert "Улучшенная версия промпта:" not in текст
    assert отчёт["improved"] not in текст
    # И финальная строка не отсылает к блоку, которого нет.
    assert "Действуй по улучшенной версии" not in текст, текст[-300:]
    assert "Действуй по промпту пользователя" in текст, текст[-300:]


# ═══════════════════════════════════════════════════════════════════════
# 3. Порядок урезания фиксирован и режет только наши блоки
# ═══════════════════════════════════════════════════════════════════════
def test_порядок_ступеней_именно_такой():
    """Харнесс уходит первым, хвост советов вторым, текст пользователя последним."""
    отчёт = build_report(ПРОМПТ_СРЕДНЕЙ_СТУПЕНИ, "claude-opus-5")
    находки = [f for f in отчёт["findings"] if not f.get("always")]
    assert отчёт.get("harness"), "вход подобран неудачно: харнесса нет, резать нечего"
    assert len(находки) > хук._СОВЕТОВ_УРЕЗАННО, "вход подобран неудачно: советов мало"

    ступени = [хук._собрать(отчёт, с) for с in range(хук._ПОСЛЕДНЯЯ_СТУПЕНЬ + 1)]
    блок_харнесса = "\nКак запускать: %s" % отчёт["harness"]["command"]

    assert блок_харнесса in ступени[0]
    for с in (1, 2, 3):
        assert блок_харнесса not in ступени[с], "харнесс пережил ступень %d" % с

    for с in (0, 1):
        assert находки[хук._СОВЕТОВ_УРЕЗАННО]["title"] in ступени[с], (
            "хвост советов срезан раньше времени, ступень %d" % с)
    for с in (2, 3):
        assert находки[хук._СОВЕТОВ_УРЕЗАННО]["title"] not in ступени[с], (
            "хвост советов пережил ступень %d" % с)

    for с in (0, 1, 2):
        assert отчёт["improved"] in ступени[с], (
            "текст пользователя срезан раньше времени, ступень %d" % с)
    assert отчёт["improved"] not in ступени[3]


def test_советы_режутся_с_хвоста_и_целиком():
    """Совет и его оговорка — одна единица: оговорка без совета бессмысленна.

    Оговорка объясняет, КОГДА совет не применяется. Оторвите её от совета — и
    останется голое поручение, то самое, ради обезвреживания которого оговорку
    и добавляли.
    """
    отчёт = build_report(ПРОМПТ_СРЕДНЕЙ_СТУПЕНИ, "claude-opus-5")
    находки = [f for f in отчёт["findings"] if not f.get("always")]
    текст = хук._собрать(отчёт, 2)
    for f in находки[:хук._СОВЕТОВ_УРЕЗАННО]:
        assert f["title"] in текст, f["id"]
        if f.get("unless"):
            assert f["unless"] in текст, "совет без оговорки: %s" % f["id"]
    # Порядок сохранён: показаны ПЕРВЫЕ три, а не произвольные три.
    места = [текст.index(f["title"]) for f in находки[:хук._СОВЕТОВ_УРЕЗАННО]]
    assert места == sorted(места), места


def test_урезание_не_трогает_чужого():
    """Всё, что снимает урезание, написано нами — ни одного чужого символа.

    Проверяем вычитанием: то, что есть на ступени 0 и пропало на последней,
    целиком собирается из наших же строк (шапка, советы, ссылки на правила,
    служебные абзацы) и не содержит длинных строк текста пользователя.
    """
    отчёт = build_report(ПРОМПТ_СРЕДНЕЙ_СТУПЕНИ, "claude-opus-5")
    полный = хук._собрать(отчёт, 0)
    урезанный = хук._собрать(отчёт, хук._ПОСЛЕДНЯЯ_СТУПЕНЬ)
    пропало = [с for с in полный.splitlines() if с not in урезанный]
    assert пропало, "ступени ничего не сняли — резать нечем"
    наше = {отчёт["harness"]["command"], "Улучшенная версия промпта:"}
    for с in пропало:
        if not с.strip():
            continue
        принадлежит_нам = (
            с.startswith("- ") or с.startswith("  неприменимо:")
            or any(з in с for з in наше)
            or с.startswith("(Действуй по улучшенной версии")
        )
        # Всё прочее пропавшее обязано быть текстом улучшенной версии, который
        # уходит вместе со СВОИМ блоком целиком, а не кусками.
        assert принадлежит_нам or с in отчёт["improved"], "пропала чужая строка: %r" % с


