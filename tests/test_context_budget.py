def test_настоящий_запуск_хука_укладывается_в_потолок():
    """Через ту же дверь, что и Claude Code: файл, stdin, JSON на выходе.

    Всё выше меряет функцию; здесь меряется то, что реально уедет в контекст.
    """
    промпт = max(КОРПУС, key=lambda пара: len(пара[0]))[0]
    среда = dict(os.environ, ANTHROPIC_MODEL="claude-opus-5")
    готово = subprocess.run(
        [sys.executable, str(_КОРЕНЬ / "hooks" / "nativeprompt_hook.py")],
        input=json.dumps({"prompt": промпт}), capture_output=True, text=True,
        cwd=str(_КОРЕНЬ), env=среда)
    assert готово.returncode == 0, готово.stderr[:400]
    контекст = json.loads(готово.stdout)["hookSpecificOutput"]["additionalContext"]
    assert len(контекст) <= хук.ПОТОЛОК_КОНТЕКСТА, len(контекст)
    assert "контекст урезан" in контекст, контекст[:200]
