"""Цена хука измерима: бюджет контекста, который платится на КАЖДОМ промпте.

`hooks/nativeprompt_hook.py` висит на `UserPromptSubmit` и подмешивает разбор к
каждому отправленному промпту. Значит его размер платится всегда — и до этого
круга никто не знал, сколько именно. Замер по корпусу давал худший случай 3528
символов, причём число росло само: когда бюджет только задумывался, тот же
замер давал 3016, а потом к каждому совету добавилась строка «неприменимо: …»,
и цена выросла на пятьсот символов, ничего не сломав и никого не предупредив.

У потолка есть известная ловушка: тест сторожит ТОЛЬКО потолок, и тогда
опубликованное число тихо расходится с кодом — потолок соблюдён, а цифра
в документации устарела. Поэтому здесь два разных теста:
`test_контекст_всегда_в_пределах_потолка` сторожит гарантию, а
`test_опубликованный_худший_случай_не_устарел` — само число в документации.

Пять граней:

    1. потолок соблюдён на всём корпусе × три модели;
    2. потолок РЕЖЕТ (без урезания корпус его пробивает) — иначе он украшение;
    3. текст пользователя цел или отсутствует целиком, никогда не обрезан;
    4. порядок урезания фиксирован и режет только наши блоки;
    5. пометка об урезании есть ровно тогда, когда что-то урезано, и называет
       только то, что действительно убрано.
"""

from __future__ import annotations

import importlib.util
import io
import json
import os
import pathlib
import re
import subprocess
import sys

import pytest

from nativeprompt.explain import build_report

# Корпус и модели — из test_invariant: второй копии живых промптов не заводим,
# две копии разойдутся так же, как расходились две копии одной регулярки.
from test_invariant import КОРПУС, МОДЕЛИ

_КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent


def _загрузить_хук():
    """Хук лежит вне пакета (`hooks/`), поэтому грузим его по пути.

    Именно ТОТ файл, который Claude Code запускает по settings.json, а не его
    копию: двадцать второй круг уже находил дефект, живший только в хуке,
    потому что тесты смотрели исключительно в пакет.
    """
    спец = importlib.util.spec_from_file_location(
        "nativeprompt_hook", _КОРЕНЬ / "hooks" / "nativeprompt_hook.py")
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


хук = _загрузить_хук()

_ИМЕНА = [f"{i:02d}_{c[:36]}" for i, (_, c) in enumerate(КОРПУС)]

#: Худший случай контекста хука на корпусе × МОДЕЛИ, в символах, ПОСЛЕ урезания.
#: Число живое: любой новый промпт в корпусе, новое правило или лишнее слово в
#: оговорке его меняют — и тогда краснеет `test_опубликованный_худший_случай_
#: не_устарел`, а не тихо устаревает строчка в README.
ХУДШИЙ_СЛУЧАЙ = 1729

#: Синтетический промпт, на котором работает СРЕДНЯЯ ступень урезания (хвост
#: списка советов). Корпус её не задевает ни разу: там либо всё помещается,
#: либо текст пользователя такой большой, что помогает только снятие блока
#: «улучшенная версия». Без этого входа ступень 2 была бы мёртвым кодом,
#: прикрытым зелёными тестами.
ПРОМПТ_СРЕДНЕЙ_СТУПЕНИ = (
    "Не мог бы ты ОБЯЗАТЕЛЬНО поправить вывод? Думай пошагово и перепроверь себя. "
    "Вот лог:\n```\nERROR: boom\n```\n"
    + "Также посмотри соседние модули и опиши, что там происходит. " * 11
)


def _контексты():
    """Все непустые контексты по корпусу × МОДЕЛИ, с пометкой, откуда каждый."""
    for промпт, причина in КОРПУС:
        for модель in МОДЕЛИ:
            отчёт = build_report(промпт, модель)
            текст = хук.build_context(отчёт)
            if текст:
                yield текст, отчёт, "%s | %s" % (причина, модель)


