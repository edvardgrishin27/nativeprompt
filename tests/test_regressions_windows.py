def test_флагманский_пример_readme_совпадает_с_живым_выводом():
    """Доки трижды расходились с кодом — пришиваем ключевой пример к поведению.

    В README это главный аргумент: один промпт, два вендора, разные правки.
    После перевода правила в предупреждение статичный пример обещал вырезанную
    фразу, которой в выводе больше нет. Такое расхождение бьёт по единственному,
    ради чего инструмент существует, — доверию к его заявлениям.
    """
    from nativeprompt.explain import build_report

    p = ("Не мог бы ты пожалуйста ОБЯЗАТЕЛЬНО починить баг в логине, "
         "думай пошагово и обязательно перепроверь себя. Покажи только самое важное.")

    claude = build_report(p, "claude-opus-5")
    # У Claude «думай пошагово» остаётся, «перепроверь себя» помечено, но цело.
    assert "думай пошагово" in claude["improved"]
    assert "перепроверь себя" in claude["improved"]
    assert "opus5-remove-verification" in {f["id"] for f in claude["findings"]}

    codex = build_report(p, "gpt-5.6")
    # У Codex ровно наоборот: цепочку рассуждений вырезаем, фразу не трогаем.
    assert "думай пошагово" not in codex["improved"]
    assert "перепроверь себя" in codex["improved"]

    # И дословная сверка: первая строка переписанного промпта обязана
    # присутствовать в README. Доки расходились с кодом четыре круга подряд —
    # проверка «фраза где-то есть» этого не ловила, нужна именно дословная.
    корень = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for файл, отчёт in (("README.ru.md", claude), ("README.ru.md", codex)):
        текст = io.open(os.path.join(корень, файл), encoding="utf-8").read()
        первая = отчёт["improved"].split("\n")[0].strip()
        assert первая in текст, "README разошёлся с живым выводом: %r" % первая[:70]


