def _сгенерировать_фаззер(seed=_ЗЕРНО, итераций=_ИТЕРАЦИЙ):
    """2–5 случайных кирпичей, склеенных случайным разделителем, под
    случайную (но детерминированную) модель — на каждую итерацию."""
    rng = Random(seed)
