def test_маска_и_предикат_никогда_не_расходятся():
    """Структурная страховка от повторения корня: источник ОДИН.

    Проверяем на корпусе, что «хвост внутри кода» по предикату совпадает с
    «хвост замаскирован» по маске. Пока обе функции читают `code_regions`,
    совпадение обязано быть; тест покраснеет в тот день, когда кто-то заведёт
    второе представление о границах кода.
    """
    from nativeprompt.analyze import mask_code, tail_inside_code
    for промпт, _ in КОРПУС:
        if not промпт.strip():
            continue
        маска = mask_code(промпт)
        i = len(промпт) - 1
        while i >= 0 and промпт[i].isspace():
            i -= 1
        замаскирован = i >= 0 and маска[i] != промпт[i]
