"""Один инвариант вместо россыпи гардов (план 0.2.0, шаг 2).

Восемь кругов независимого ревью находили в инструменте один и тот же класс
дефектов: регулярки, правящие текст пользователя, молча портили содержание —
уничтожали слова («Обдумай пошагово» → «Об.», «настолько важное» →
«насвсё…»), переворачивали смысл, ломали данные в кавычках, склеивали два
поручения в одно. Каждый круг чинил предъявленный вход, а не класс, — и
следующий круг находил новый вход того же класса. Шаг 1 убрал почти все такие
операции; остались только `_soften_caps` (регистр КАПС-слов) и `_strip_vague`
(снятие вежливой обёртки в начале), плюс добавление секций-плейсхолдеров.

Здесь — ОДНО свойство, которое субсумирует весь класс, а не пины на
конкретные предъявленные входы:

    каждое содержательное слово исходного промпта присутствует в improved;
    единственное разрешённое исключение — слова снятой вежливой обёртки;
    регистр не считается.

и обратное к нему: improved не выдумывает слов, которых не было ни в
исходнике, ни в шаблонах добавляемых секций.

Голого сравнения по .lower() недостаточно — задание прямо предупреждает
(мутация М1): понижение регистра не меняет множество слов «в нижнем
регистре», поэтому потерю РЕГИСТРА в URL/пути/KEY=VALUE такое сравнение не
увидит. Поэтому здесь три грани одного инварианта, а не одна:

    1. найти_потери      — ни одно слово не исчезло (с поправкой на обёртку);
    2. _защищённые_токены — регистрозначимые токены (URL, путь, KEY=VALUE)
                             выжили ПОБУКВЕННО, не только «по составу слов»;
    3. _защищённое_разрешение — «Можешь не X» — это разрешение, а не вежливая
                             обёртка, и обязано остаться нетронутым целиком.

Проверено на двух источниках входов: корпус (~40 живых промптов, у каждого —
своя причина существования) и фаззер (500 детерминированных склеек кирпичей
из тех же классов, что и корпус). Как в test_regressions_windows.py: у
каждого случая в комментарии — ПОЧЕМУ он здесь, какой именно дефект прошлых
кругов сторожит, а не что он буквально содержит.
"""

