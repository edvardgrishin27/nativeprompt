# ── инвариант №5: `action` правила = то, что rewrite действительно делает ──
#
# Тринадцатый круг нашёл дыру в самой правке двенадцатого. Маркер стали
# считать по факту (`id in applied`), но `_ACTION_MARK["warn"]` и
# `_UNTOUCHED_MARK` — ОДИН И ТОТ ЖЕ глиф `[!]`. И `codex-agents-md`, объявленный
# `warn`, единственный из warn-правил реально дописывал в промпт «(Заметка:
# вынесите правила в AGENTS.md…)». Получалась обратная ложь: инструмент сделал
# больше, чем сказал, — знак «не притронулся» при изменённом тексте.
#
# Заплатка на глиф не помогла бы: причина в том, что декларация правила и
# поведение кода жили порознь и никто их не сверял. Свойство ниже сверяет их
# структурно — по AST, без запусков, — и потому не зависит от того, догадался
# ли я про конкретный вход.
def _применяемые_правила():
    """id, которые `rewrite()` способна положить в `applied` — читаем из AST.

    Не список руками: рукописный список расходится с кодом ровно так же, как
    разошлась декларация `action`.
    """
    исходник = inspect.getsource(_rewrite_module.rewrite)
    дерево = ast.parse(textwrap.dedent(исходник))
    найденные = set()
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call) or not узел.args:
            continue
        это_append = (isinstance(узел.func, ast.Attribute)
                      and узел.func.attr == "append"
                      and isinstance(узел.func.value, ast.Name)
                      and узел.func.value.id == "applied")
        это_add = isinstance(узел.func, ast.Name) and узел.func.id == "add"
        if not (это_append or это_add):
            continue
        # У `add(rule_id, tag, label, content)` правило — только первый
        # аргумент; остальные строки это разметка, их брать нельзя.
        for кусок in ast.walk(узел.args[0]):
            if isinstance(кусок, ast.Constant) and isinstance(кусок.value, str):
                найденные.add(кусок.value)
    return найденные


