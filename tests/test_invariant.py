# ── инвариант №4: маркер отчёта не может обещать больше, чем сделано ──
#
# Двенадцатый круг: `[+]` печатался по объявленному в правиле `action`, а не по
# факту. Два always-правила с `action: add` (`fable5-ground-progress`,
# `opus48-encourage-subagents`) выглядели в отчёте ровно как `opus5-concise`,
# который действительно дописывает «Ответь кратко», — но не дописывали ничего.
# И наоборот: XML-обёртка применялась, а в `applied` не попадала, так что
# потребитель `--json` видел в `improved` правку, о которой ему не сказали.
#
# Ни один из 281 теста этого не заметил. Свойство ниже закрывает оба конца
# разом: знак действия печатается тогда и только тогда, когда правило реально
# сработало, а всё в `applied` реально меняет текст.
_ЗНАКИ_ДЕЙСТВИЯ = {"[+]", "[-]", "[~]"}


def _нормализованный(текст):
    """Как инструмент приводит промпт ДО правок: пустые строки в начале и
    пробелы в конце. Ведущий отступ первой строки значим и остаётся."""
    return re.sub(r"\A(?:[ \t]*\r?\n)+", "", текст).rstrip()
_ИМЕНА_КОРПУСА = [f"{i:02d}_{c[:36]}" for i, (_, c) in enumerate(КОРПУС)]
_ВСЕ_ID_ПРАВИЛ = {
    r["id"]
    for f in catalog.available_families()
    for r in catalog.load_family(f).get("rules", [])
}


def _разобрать_маркеры(отчёт):
    """{id правила: маркер} — читаем через ту же функцию, что и рендер."""
    from nativeprompt.explain import _mark
    return {f["id"]: _mark(f, отчёт["applied"]) for f in отчёт["findings"]}


@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,_", КОРПУС, ids=_ИМЕНА_КОРПУСА)
def test_знак_действия_только_у_реально_сработавшего(промпт, _, модель):
    отчёт = build_report(промпт, модель)
    for rid, знак in _разобрать_маркеры(отчёт).items():
        if знак in _ЗНАКИ_ДЕЙСТВИЯ:
            assert rid in отчёт["applied"], (
                "маркер %s обещает правку, которой нет: %s" % (знак, rid))


