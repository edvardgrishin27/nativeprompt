    for _ in range(итераций):
        n = rng.randint(2, 5)
        части = [rng.choice(КИРПИЧИ) for _ in range(n)]
        разделитель = rng.choice(РАЗДЕЛИТЕЛИ)
        модель = rng.choice(МОДЕЛИ)
        входы.append((разделитель.join(части), модель))
    return входы


