# nativeprompt/__init__.py делает `from .rewrite import rewrite`, из-за чего
# атрибут ПАКЕТА `nativeprompt.rewrite` указывает на ФУНКЦИЮ rewrite, а не на
# модуль (классическая ловушка `from .submodule import name_same_as_submodule`
# — __init__.py импортирует имя `rewrite` последним и перетирает им ссылку на
# сам подмодуль). importlib.import_module берёт модуль из sys.modules по
# полному имени и не зависит от того, что переопределил __init__.py.
_rewrite_module = importlib.import_module("nativeprompt.rewrite")

#: Три модели с разными наборами правил (задание шага 2) — дефекты прошлых
#: кругов сидели именно в разных ветках: opus-5 (opus5-remove-verification),
#: fable-5 (fable5-no-show-thinking), codex (codex-no-forced-cot/-lean).
МОДЕЛИ = ("claude-opus-5", "claude-fable-5", "gpt-5.6")

_СЛОВО = re.compile(r"\w[\w-]*")


def _слова_списком(текст):
    """Слова в порядке появления, с повторами — для проверки кратности."""
    return re.findall(r"\w[\w-]*", текст.lower())


def _слова(текст):
    """Множество содержательных слов текста без учёта регистра."""
    return set(_СЛОВО.findall(текст.lower()))


# ── источник правды №1: сама _strip_vague, а не переписанный список слов ──
def _обёртка_вежливости(original):
    """Слова, которые _strip_vague реально сняла бы именно с этого текста.

    Не хардкодим финальный список слов на глаз: спрашиваем саму функцию —
    единственный источник правды здесь (`_VAGUE_OPENER` в rewrite.py). Так
    правка формулы обёртки (новый синоним, новая форма) подхватывается
    тестом сама, без риска, что копия в задании разойдётся с кодом при первой
    же правке.

    Не годится для мутации М2 (см. _защищённое_разрешение ниже): это
    спрашивает саму _strip_vague, поэтому не ловит порчу ВНУТРИ неё —
    сломай гард отрицания как угодно, и «обёртка» сломается вместе с ним и
    оправдает любую его потерю. Для этого нужна проверка, не зависящая от
    того, работает ли сама _strip_vague правильно.
    """
    original = original.strip()
    stripped = outside_code(_strip_vague, original)
    return _слова(original) - _слова(stripped)


# ── источник правды №2: AST функций rewrite()/_assemble(), а не список рукам
def _строковые_константы(fn):
    """Все строковые литералы в исходнике функции (докстринг тоже — он не
    вредит: слова из докстринга лишь расширяют разрешённый словарь, а не
    сужают его)."""
    src = textwrap.dedent(inspect.getsource(fn))
    tree = ast.parse(src)
    return [
        n.value
        for n in ast.walk(tree)
        if isinstance(n, ast.Constant) and isinstance(n.value, str)
    ]


def _слова_из_текстов(тексты):
    слова = set()
    for текст in тексты:
        текст = re.sub(r"%[sd]", " ", текст)  # %s/%d — формат-плейсхолдер, не слово
        слова |= _слова(текст)
    return слова


#: Всё, что rewrite.rewrite() имеет право ДОБАВИТЬ: плейсхолдеры семи
#: add(...)-вызовов, два блока «Краткость»/«Автономность», имена XML-тегов и
#: обвязка _assemble (<instructions>, "note" и т. п.). Собрано из AST
#: реального кода, а не переписано руками — см. задание: «собери их из кода
#: или из констант, а не переписывай руками».
ДОБАВКИ = _слова_из_текстов(
    _строковые_константы(_rewrite_module.rewrite)
    + _строковые_константы(_rewrite_module._assemble)
)


#: Полный список слов, которые инструменту РАЗРЕШЕНО убирать. Захардкожен
#: намеренно: это обещание инструмента, а не копия его реализации.
СЛОВАРЬ_ВЕЖЛИВОСТИ = {
    "не", "мог", "могли", "бы", "ты", "вы", "можешь", "ли", "пожалуйста",
    "could", "can", "would", "you", "please",
}


def найти_кратность(original, improved):
    """Слова, которых стало МЕНЬШЕ, чем было.

    Сравнение множеств слепо к дубликатам: молча удалённое повторяющееся
    предложение («Сделай бэкап базы. Сделай бэкап базы.» → одно) множество не
    меняет. А это ровно тот класс порчи, от которого проект и отказался.
    """
    было = collections.Counter(_слова_списком(original))
    стало = collections.Counter(_слова_списком(improved))
    return {w: было[w] - стало[w] for w in было if было[w] > стало.get(w, 0)}


def найти_потери(original, improved):
    """Слова original, которых нет ни в improved, ни в разрешённой обёртке.

    ВАЖНО, как считаются «разрешённые потери». Первая редакция спрашивала саму
    `_strip_vague` — что она сняла с этого текста. Это тавтология, и ревью
    доказало её делом: обёртка, начавшая резать в СЕРЕДИНЕ текста после
    код-спана, и обёртка, съевшая содержательное слово, проходили зелёными —
    «разрешённые потери» росли вместе с багом и оправдывали его.
    Теперь разрешение считается из ДВУХ независимых источников сразу:

      1. ПОЗИЦИЯ — совпадение `_VAGUE_OPENER` в начале ВСЕГО текста. Ничего,
         кроме начала, снимать нельзя, поэтому потеря из середины не может
         быть оправдана ничем;
      2. СЛОВАРЬ — пересечение со списком вежливых слов, захардкоженным ниже.
         Это ДОГОВОР инструмента, а не повтор его кода: расширь шаблон обёртки
         до настоящего глагола, и слово всё равно окажется вне разрешённых.

    Ни один из источников не спрашивает тело `_strip_vague`.
    """
    начало = _VAGUE_OPENER.match(original.strip())
    if not начало:
        разрешено = set()
    else:
        # Хвостовое «пожалуйста» снимается вторым проходом уже ПОСЛЕ обёртки и в
        # её совпадение не входит — «Не мог бы ты, пожалуйста, почини» давало
        # ложную потерю на правильном коде. Разрешаем вежливые слова, идущие
        # сразу за совпадением, но только их: словарь по-прежнему решает.
        хвост = re.match(r"[\s,]*(?:пожалуйста|please)[\s,]*", original.strip()[начало.end():], re.I)
        разрешено = _слова(начало.group(0) + (хвост.group(0) if хвост else ""))
        разрешено &= СЛОВАРЬ_ВЕЖЛИВОСТИ
    return _слова(original) - _слова(improved) - разрешено


def найти_выдумки(original, improved):
    """Слова improved, которых нет ни в original, ни в добавляемых шаблонах."""
    return _слова(improved) - _слова(original) - ДОБАВКИ


# ── грань 2: регистрозначимые токены переживают ножи ПОБУКВЕННО ───────────
def _защищённые_токены(original):
    """Непробельные куски вокруг капс-слова с «занятыми» соседями — там, где
    has_safe_neighbors говорит «нет», регистр значим (URL, путь, KEY=VALUE).

    Мутация М1 из задания: если из _soften_caps убрать проверку соседей, КАПС
    в `MODE=CRITICAL` и в URL начнёт понижаться. Но найти_потери сравнивает
    по .lower() — множество слов «critical»/«CRITICAL» в нижнем регистре
    совпадает что до, что после порчи, — потерю НЕ увидит. Нужна отдельная,
    побуквенная проверка ровно тех токенов, которые сам инструмент считает
    регистрозначимыми (has_safe_neighbors — тот же гард, что в _soften_caps
    и в детекторе _c_pushy_caps, общий источник правды, а не копия).
    """
    токены = []
    for m in CAPS_WORD.finditer(original):
        if has_safe_neighbors(original, m.start(), m.end()):
            continue  # обычный КАПС посреди текста — регистр можно менять
        left, right = m.start(), m.end()
        while left > 0 and not original[left - 1].isspace():
            left -= 1
        while right < len(original) and not original[right].isspace():
            right += 1
        токены.append(original[left:right])
    return токены


# ── грань 3: «Можешь не X» — разрешение, а не обёртка ──────────────────────
def _защищённое_разрешение(original):
    """Слова начала текста, если это «Можешь не X» — разрешение, а не
    вежливая обёртка (и снимать их нельзя).

    Ровно то условие, при котором _strip_vague ОБЯЗАНА быть no-op (см. её
    собственный docstring в rewrite.py). Проверяем это НЕЗАВИСИМО от самой
    _strip_vague: используем живые _VAGUE_OPENER/_NEGATION (форма обёртки и
    отрицания — из rewrite.py, источник правды, не переписана на глаз), но
    решение «трогать нельзя» принимает ТЕСТ, а не спрашивает функцию. Иначе
    проверка была бы тавтологией — см. предупреждение в _обёртка_вежливости
    выше: убери гард отрицания (мутация М2) — «обёртка» сломается вместе с
    ним и оправдает любую потерю, инвариант промолчит.

    Возвращает слова, которые обязаны выжить целиком в improved, либо пустое
    множество, если это не тот случай.
    """
    text = original.strip()
    m = _VAGUE_OPENER.match(text)
    if not m:
        return set()
    первая_фраза = re.split(r"[,.!?\n]", text[m.end():], maxsplit=1)[0]
    if not _NEGATION.search(первая_фраза):
        return set()  # обычная вежливость без отрицания — снимать можно
    return _слова(text[: m.end()])


def _проверить(prompt, model, причина=""):
    """Прогнать один промпт через build_report и все три грани инварианта.

    Возвращает СПИСОК описаний нарушений, а не падает по первому assert —
    фаззер собирает все провалы разом (один пойманный дефект не должен
    прятать остальные девятнадцать таких же).
    """
    report = build_report(prompt, model)
    if report.get("error"):
        return []  # модель не распознана — improve не вызывался, нечего проверять
    improved = report["improved"]
    метка = f" [{причина}]" if причина else ""
    беды = []

    потери = найти_потери(prompt, improved)
    if потери:
        беды.append(
            f"потеряны слова{метка} (модель {model})\nвход: {prompt!r}\n"
            f"improved: {improved!r}\nпотеряно: {sorted(потери)}"
        )

    for токен in _защищённые_токены(prompt):
        if токен not in improved:
            беды.append(
                f"искажён регистрозначимый токен{метка} (модель {model})\n"
                f"вход: {prompt!r}\nimproved: {improved!r}\nтокен: {токен!r}"
            )

    # Пробелы значимы в таблицах и отступах: схлопывание их — тоже подмена.
    if prompt.strip() and "  " in prompt:
        сдвоенных_было = prompt.count("  ")
        if improved.count("  ") < сдвоенных_было:
            беды.append(
                f"схлопнуты пробелы{метка} (модель {model})\n"
                f"вход: {prompt!r}\nimproved: {improved!r}"
            )

    кратность = найти_кратность(prompt, improved)
    разрешено_меньше = СЛОВАРЬ_ВЕЖЛИВОСТИ
    просело = {w: n for w, n in кратность.items() if w not in разрешено_меньше}
    if просело:
        беды.append(
            f"слов стало меньше, чем было{метка} (модель {model})\n"
            f"вход: {prompt!r}\nimproved: {improved!r}\nпросело: {просело}"
        )

    защищено = _защищённое_разрешение(prompt)
    if защищено and not (защищено <= _слова(improved)):
        беды.append(
            f"разрешение превращено в обёртку и снято{метка} (модель {model})\n"
            f"вход: {prompt!r}\nimproved: {improved!r}"
        )

    выдумки = найти_выдумки(prompt, improved)
    if выдумки:
        беды.append(
            f"improved содержит слова не из промпта и не из шаблонов{метка} "
            f"(модель {model})\nвход: {prompt!r}\nimproved: {improved!r}\n"
            f"лишнее: {sorted(выдумки)}"
        )

    return беды


