"""Отказ переписывать: инструмент умеет сказать «здесь работы нет».

До этого круга `improve` всегда что-нибудь возвращал. Мета-промпт — инструкция
вашей же модели «перепиши промпт под правила» — печатался ВСЕГДА, даже когда
правила молчали: тогда в него уезжала заглушка «(существенных правок правила не
требуют)». Человек получал поручение переписать промпт, который переписывать не
надо, и отдавал его модели, а модель работу находила, потому что её попросили.
Правка ради правки — ровно то, от чего инструмент должен защищать.

Решение «переписывать или нет» принимается ДО переписи и явно.

Здесь проверяется чистая функция `nothing_to_do` и обе её ветки на живых
промптах из `examples/prompts.md` — тех самых, что стоят в README как демо:

  • «Добавь тест в @src/foo.py …» — пример №7, «хорошо оформленный промпт
    (правок почти нет — так и надо)». Находок нет вовсе → отказ;
  • «Не мог бы ты пожалуйста ОБЯЗАТЕЛЬНО …» — пример №1, семь находок, две из
    них требуют вашего решения → мета-промпт на месте.

Пины привязаны к файлу примеров, а не к своей копии строк: разойдётся демо —
покраснеет тест, а не выйдет тихо расхождение между README и поведением.
"""

import copy
import io
import os

import pytest

from nativeprompt.explain import ОТКАЗ, build_report, nothing_to_do, render_report

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
МОДЕЛИ = ("claude-opus-5", "claude-fable-5", "gpt-5.6")


def _промпты_из_примеров():
    """Промпты ровно из examples/prompts.md — они там идут цитатой «> …»."""
    текст = io.open(os.path.join(КОРЕНЬ, "examples", "prompts.md"),
                    encoding="utf-8").read()
    return [s[2:].strip() for s in текст.splitlines() if s.startswith("> ")]


def _пример(кусок):
    подходят = [p for p in _промпты_из_примеров() if кусок in p]
    assert len(подходят) == 1, "в examples/prompts.md нет ровно одного промпта с %r" % кусок
    return подходят[0]


ХОРОШИЙ = _пример("@src/foo.py")          # пример №7
СЫРОЙ = _пример("ОБЯЗАТЕЛЬНО")            # пример №1
БЕЗ_КОНТЕКСТА = _пример("валидации email")  # пример №2


@pytest.mark.parametrize("model", МОДЕЛИ)
def test_хорошему_промпту_инструмент_отказывает_в_переписи(model):
    """Первая ветка: не-always находок ноль — сказать нечего, и говорить не надо."""
    отчёт = build_report(ХОРОШИЙ, model)
    assert [f for f in отчёт["findings"] if not f.get("always")] == []
    assert nothing_to_do(отчёт) is True


def test_отказ_печатается_первым_и_вместо_метапромпта():
    отчёт = build_report(ХОРОШИЙ, "claude-opus-5")
    экран = render_report(отчёт)
    assert экран.startswith(ОТКАЗ), экран[:200]
    assert "МЕТА-ПРОМПТ" not in экран, "мета-промпт напечатан там, где переписывать нечего"
    # Разбор при этом никуда не делся: отказ — не молчание.
    assert "МОДЕЛЬ:" in экран and "УЛУЧШЕННЫЙ ПРОМПТ" in экран


def test_отказ_объясняет_отсутствие_метапромпта():
    """Пустое место там, где вчера был блок, читается как поломка. Поэтому
    инструмент говорит, почему не печатает, а не просто не печатает."""
    экран = render_report(build_report(ХОРОШИЙ, "claude-opus-5"))
    assert "мета-промпт не печатаю" in экран


def test_сырому_промпту_мета_промпт_остаётся():
    """Вторая сторона пина: там, где работа есть, ничего не пропало."""
    отчёт = build_report(СЫРОЙ, "claude-opus-5")
    assert nothing_to_do(отчёт) is False
    экран = render_report(отчёт)
    assert ОТКАЗ not in экран
    assert "МЕТА-ПРОМПТ" in экран


@pytest.mark.parametrize("model", МОДЕЛИ)
def test_сырой_промпт_нигде_не_проходит_как_готовый(model):
    assert nothing_to_do(build_report(СЫРОЙ, model)) is False


def test_предупреждение_держит_мета_промпт_на_месте():
    """`warn` — совет, который требует ВАШЕГО решения: инструмент такие правила
    по договору помечает, а не режет. Пока хоть один такой горит, «переписывать
    нечего» — неправда, сколько бы правок инструмент ни применил сам."""
    отчёт = build_report("Покажи только самое важное по @a.py", "claude-opus-5")
    предупреждения = [f for f in отчёт["findings"]
                      if not f["always"] and f["action"] == "warn"]
    assert предупреждения, "промпт перестал ловить warn — пин потерял смысл"
    assert nothing_to_do(отчёт) is False
    assert "МЕТА-ПРОМПТ" in render_report(отчёт)


def test_нож_отработал_и_добавить_нечего():
    """Вторая ветка на живом входе: сработало одно правило, и его инструмент
    закрыл сам (понизил КАПС). Умной переписи тут работы не осталось."""
    отчёт = build_report("ОБЯЗАТЕЛЬНО почини @a.py и прогони тесты, верни только дифф",
                         "claude-opus-5")
    сработали = [f for f in отчёт["findings"] if not f["always"]]
    assert [f["id"] for f in сработали] == ["claude-dial-caps"]
    assert nothing_to_do(отчёт) is True
    assert "ОБЯЗАТЕЛЬНО" not in отчёт["improved"], "нож не отработал — пин мимо"
    # Отказ называет, что именно закрыл: список находок под ним не пуст, и без
    # этой строки он читался бы как противоречие самому себе.
    экран = render_report(отчёт)
    assert "закрыл сам: claude-dial-caps" in экран, экран[:300]


@pytest.mark.parametrize("model", МОДЕЛИ)
def test_плейсхолдер_это_не_закрытое_правило(model):
    """Граница второй ветки — и единственное место, где реализация строже буквы
    задания.

    «Напиши функцию валидации email» — три находки, и формально все три стоят в
    `applied`: инструмент дописал секции. Но дописал он их ПЛЕЙСХОЛДЕРАМИ
    ‹уточните: …› — то есть не закрыл правила, а передал их вам. Скажи здесь
    инструмент «переписывать нечего», отказ стоял бы прямо над текстом, который
    без человека не дописан, а самопроверка `--verify` тут же положила бы те же
    правила в корзину «оставлено вам»: две половины одного инструмента говорили
    бы разное об одном промпте.

    Тот же вход ловит и первый пример из examples/prompts.md на Fable 5: там
    нет ни одного `warn`-правила поколения, и без этой проверки самый сырой
    промпт демо проходил бы как готовый.
    """
    отчёт = build_report(БЕЗ_КОНТЕКСТА, model)
    сработали = [f for f in отчёт["findings"] if not f["always"]]
    assert сработали and all(f["id"] in отчёт["applied"] for f in сработали), (
        "пин потерял смысл: не все находки применены, ветка и так бы не сработала")
    assert "‹" in отчёт["improved"], "плейсхолдеров нет — проверять нечего"
    assert nothing_to_do(отчёт) is False
    assert "МЕТА-ПРОМПТ" in render_report(отчёт)


def test_плейсхолдер_считается_по_расписке_а_не_по_скобкам():
    """Угловые скобки мог написать и сам автор — его текст не наша недоделка.

    Считаем по расписке сборщика (`insertions`), поэтому промпт с ‹…› внутри и
    без наших вставок отказу не мешает.
    """
    отчёт = {
        "original": "x", "target": {"family": "claude"},
        "findings": [{"id": "a", "action": "remove", "always": False}],
        "applied": ["a"],
        "improved": "почини ‹это место› в @a.py",
        "insertions": [],
    }
    assert nothing_to_do(отчёт) is True
    # А та же скобка внутри НАШЕЙ вставки — уже недоделка.
    отчёт["insertions"] = [(7, 18)]
    assert отчёт["improved"][7:18].startswith("‹")
    assert nothing_to_do(отчёт) is False


def test_отчёт_с_ошибкой_это_не_отказ():
    """Модель не определилась — разбора не было, и утверждать по нему нечего.
    Тихое True здесь означало бы «промпт в порядке» по отчёту, которого нет."""
    assert nothing_to_do({"original": "Почини баг", "target": {},
                          "error": "model_unknown"}) is False


def test_функция_чистая():
    """Ни печати, ни окружения, ни правки отчёта — иначе её нельзя звать дважды
    (а `render_report` зовёт её один раз и печатает по одному решению)."""
    отчёт = build_report(СЫРОЙ, "claude-opus-5")
    снимок = copy.deepcopy(отчёт)
    assert nothing_to_do(отчёт) is nothing_to_do(отчёт)
    assert отчёт == снимок, "nothing_to_do поменяла отчёт"


def test_предупреждение_перевешивает_даже_полностью_применённый_набор():
    """Контракт функции, а не сегодняшнее поведение переписчика.

    Сегодня `warn`-правило в `applied` попасть не может: ветки в переписчике у
    него нет по договору «помечать, а не резать». Появится такая ветка — и без
    отдельной проверки на `warn` предупреждение уехало бы вместе с мета-промптом
    молча. Отчёт собран руками именно поэтому: собрать такой через `build_report`
    сегодня нельзя.
    """
    отчёт = {
        "original": "x", "target": {"family": "claude"},
        "findings": [
            {"id": "a", "action": "restructure", "always": False},
            {"id": "b", "action": "warn", "always": False},
        ],
        "applied": ["a", "b"],
    }
    assert nothing_to_do(отчёт) is False
    отчёт["findings"][1]["action"] = "restructure"
    assert nothing_to_do(отчёт) is True


def test_неприменённая_находка_держит_переписчика():
    """Третий кусок контракта: находка есть, инструмент её не закрыл — работа
    для умной переписи осталась, отказывать нельзя."""
    отчёт = {
        "original": "x", "target": {"family": "claude"},
        "findings": [{"id": "a", "action": "add", "always": False}],
        "applied": [],
    }
    assert nothing_to_do(отчёт) is False


def test_always_правила_не_считаются_работой():
    """`always` — это не находка в промпте, а добавление по умолчанию для
    поколения («Ответь кратко» на Opus 5). Держать из-за него мета-промпт
    значило бы никогда не отказывать на Opus 5 вовсе."""
    отчёт = build_report(ХОРОШИЙ, "claude-opus-5")
    assert [f["id"] for f in отчёт["findings"] if f.get("always")] == ["opus5-concise"]
    assert nothing_to_do(отчёт) is True


def test_json_и_ключи_отчёта_не_поехали(capsys):
    """Совместимость: отказ — это про ПЕЧАТЬ. У людей вызов хука прописан в
    settings.json, а `--json` разбирают скриптами; форма отчёта прежняя."""
    import json

    from nativeprompt.__main__ import main

    assert main(["improve", ХОРОШИЙ, "--model", "claude-opus-5", "--json"]) == 0
    отчёт = json.loads(capsys.readouterr().out)
    assert отчёт["metaprompt"], "ключ metaprompt пропал из --json"
    assert set(отчёт) >= {"original", "target", "shape", "findings", "harness",
                          "improved", "applied", "insertions", "metaprompt"}


def test_cli_печатает_отказ_и_возвращает_ноль(capsys):
    from nativeprompt.__main__ import main

    assert main(["improve", ХОРОШИЙ, "--model", "claude-opus-5"]) == 0
    вывод = capsys.readouterr().out
    assert вывод.startswith(ОТКАЗ)
    assert "МЕТА-ПРОМПТ" not in вывод


def test_флаг_no_metaprompt_и_отказ_не_ссорятся(capsys):
    """Два разных пути к одному и тому же отсутствию блока не должны давать ни
    двойного отказа, ни ошибки."""
    from nativeprompt.__main__ import main

    assert main(["improve", ХОРОШИЙ, "--model", "claude-opus-5", "--no-metaprompt"]) == 0
    вывод = capsys.readouterr().out
    assert вывод.count(ОТКАЗ) == 1
    assert "МЕТА-ПРОМПТ" not in вывод
