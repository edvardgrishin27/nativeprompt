"""Самопроверка: инструмент прогоняет собственные детекторы по своему результату.

Цикл замкнут: оптимизировал, прогнал, проверил себя. Офлайн и без модели —
те же регулярки, второй раз. Три корзины: `closed` (находка была и в тексте её больше нет), `left`
(осталась — это норма, такие правила помечают, а не режут) и `introduced`
(находки не было, а после правки есть). Третья корзина — дефект инструмента:
он сам внёс в текст то, на что сам же ругается.

До этого круга такого теста у проекта не было вовсе, и на корпусе он находил
дефект 20 раз в 18 прогонах из 171 (на двух горели обе находки сразу):

  • `claude-xml` — 10 раз. Секция «Контекст: ‹…›», которую дописывает сам
    инструмент, это и метка `контекст:` из маркеров многочастного промпта, и
    лишние символы вокруг блока кода, из-за которых `_смешаны_текст_и_код`
    начинал считать промпт смесью инструкции и данных;
  • `fable5-ground-progress` — 10 раз. Плейсхолдер «…и чинить, пока не
    пройдёт» читается `task_shape` как форма goal, и на Fable 5 зажигалось
    правило, которого в исходном промпте не было.

Чинили не подстрокой («не считать слово „Контекст:“»): такой список закрыл бы
ровно предъявленные входы и разошёлся бы с текстом добавок при первой же их
правке. Чинили РАСПИСКОЙ: `_assemble` возвращает спаны всего, что написал сам
инструмент (блоки-добавки и обе половины XML-обёртки), она едет в отчёте, и
второй прогон получает текст без неё — то есть ровно текст автора после ножей.

Здесь пять граней:

    1. главный инвариант — на корпусе × три модели и на 500 склейках фаззера
       корзина `introduced` пуста;
    2. пины на оба дефекта — с проверкой, что без вычитания находка есть,
       иначе тест зелен по случайности, а не по делу;
    3. расписка точна — снятие вставок возвращает РОВНО текст автора, во всех
       трёх форматах сборки;
    4. второй прогон не переопределяет модель — иначе половины самопроверки
       сравнивали бы находки по разным наборам правил;
    5. флаг ничего не ломает — без `--verify` вывод прежний до символа.
"""

from __future__ import annotations

import json

import pytest

from nativeprompt import detect as _detect
from nativeprompt.analyze import analyze
from nativeprompt.explain import build_report, render_verify, verify_delta
from nativeprompt.rewrite import _assemble, strip_insertions

# Корпус и модели — из test_invariant, второй копии живых промптов не заводим:
# две копии разойдутся так же, как расходились две копии одной регулярки.
from test_invariant import КОРПУС, МОДЕЛИ, _ФАЗЗЕР_ВХОДЫ, _слова

_ИМЕНА = [f"{i:02d}_{c[:36]}" for i, (_, c) in enumerate(КОРПУС)]

#: Отчёт, у которого модель не определилась. Собран руками, а не через
#: `build_report` с выдуманным именем: detect читает окружение, и на чужой
#: машине такой вызов мог бы неожиданно определиться.
ОТЧЁТ_БЕЗ_МОДЕЛИ = {"original": "Почини баг", "target": {}, "error": "model_unknown"}


# ═══════════════════════════════════════════════════════════════════════
# 1. Главный инвариант: инструмент не вносит находок в собственный результат
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_инструмент_не_вносит_находок_в_свой_результат(промпт, причина, модель):
    """Корзина `introduced` пуста — на всём корпусе и на всех трёх моделях.

    Второй assert стережёт саму самопроверку от вырождения: `verify_delta`,
    которая всегда возвращает три пустых списка, прошла бы первый assert и
    ничего не проверяла бы. Корзины обязаны разложить ВСЕ находки первого
    прогона, ни одной не потеряв и ни одну не положив в две сразу.
    """
    отчёт = build_report(промпт, модель)
    корзины = verify_delta(отчёт)
    assert корзины["introduced"] == [], "%s | %s" % (причина, корзины["introduced"])

    было = {f["id"] for f in отчёт["findings"]}
    закрыто, осталось = set(корзины["closed"]), set(корзины["left"])
    assert закрыто | осталось == было, "корзины потеряли находки первого прогона"
    assert not (закрыто & осталось), "находка попала сразу в две корзины"
    assert not (set(корзины["introduced"]) & было), "внесённое не может быть прежним"


def test_фаззер_не_вносит_находок():
    """Те же 500 детерминированных склеек, на которых проверяется инвариант слов.

    Корпус — это входы, которые кто-то придумал; фаззер собирает то, что не
    придумал никто: КАПС посреди отступного блока, вежливая обёртка перед
    таблицей, два фенса подряд. Оба дефекта, которые нашла самопроверка, жили
    ровно в таких стыках — на разметке вокруг блока кода, — поэтому фаззер
    здесь не роскошь.

    Провалы собираются все разом: один пойманный дефект не должен прятать
    остальные (та же логика, что у фаззера инварианта).
    """
    беды = []
    for промпт, модель in _ФАЗЗЕР_ВХОДЫ:
        внесено = verify_delta(build_report(промпт, модель))["introduced"]
        if внесено:
            беды.append("%s | %s\n%r" % (модель, внесено, промпт))
    assert not беды, ("%d проваленных из %d склеек (первые 3):\n\n%s"
                      % (len(беды), len(_ФАЗЗЕР_ВХОДЫ), "\n\n".join(беды[:3])))


def test_самопроверка_не_пуста_и_на_корпусе_что_то_видит():
    """Обратная сторона: машинка обязана что-то показывать, а не молчать.

    Иначе «introduced пуст» верно и у инструмента, который вообще ничего не
    делает с текстом, — а именно этим кончались прошлые круги ревью, где
    самым безопасным способом закрыть дефект было снять операцию целиком.
    """
    закрыто, осталось = set(), set()
    for промпт, _ in КОРПУС:
        for модель in МОДЕЛИ:
            корзины = verify_delta(build_report(промпт, модель))
            закрыто |= set(корзины["closed"])
            осталось |= set(корзины["left"])
    # Ножи работают по тексту автора — их правки и обязаны закрывать находки.
    assert {"claude-dial-caps", "claude-explicit-action"} <= закрыто, закрыто
    # А правила, которые помечают, а не режут, остаются человеку.
    assert {"claude-scope", "claude-verification"} <= осталось, осталось


# ═══════════════════════════════════════════════════════════════════════
# 2. Пины на оба дефекта, которые эта самопроверка нашла
# ═══════════════════════════════════════════════════════════════════════
#: Дословный вход из симуляции: закрытый блок кода + короткая инструкция
#: вокруг него. Сам по себе многочастным он не считается (текста вне блока
#: меньше порога), а с нашей секцией «Контекст:» — начинал считаться.
ВХОД_XML = "СРОЧНО перепиши функцию:\n~~~js\nfunction f(x) { return x + 1; }\n~~~"
#: Дословный вход, на котором инструмент дописывал «Проверка: ‹… и чинить,
#: пока не пройдёт›» и сам же читал свой плейсхолдер как форму задачи goal.
ВХОД_GOAL = "Сделай бэкап базы в @a.py. Сделай бэкап базы. Потом ещё раз сделай бэкап базы."


def test_своя_метка_контекста_не_рождает_находку_про_xml():
    отчёт = build_report(ВХОД_XML, "claude-opus-5")
    assert "claude-xml" not in verify_delta(отчёт)["introduced"]
    # И дефект был настоящий: по НЕвычтенному тексту находка есть. Если этот
    # assert однажды покраснеет — значит детектор перестал реагировать на нашу
    # секцию сам, и стоит перечитать, зачем ещё нужна расписка (а не удалять
    # тест).
    сырой = {f["id"] for f in analyze(отчёт["improved"], отчёт["target"])}
    assert "claude-xml" in сырой, "дефект исчез сам — проверьте, что стережёт расписка"


def test_свой_плейсхолдер_проверки_не_меняет_форму_задачи():
    отчёт = build_report(ВХОД_GOAL, "claude-fable-5")
    assert "fable5-ground-progress" not in verify_delta(отчёт)["introduced"]
    сырой = {f["id"] for f in analyze(отчёт["improved"], отчёт["target"])}
    assert "fable5-ground-progress" in сырой, "дефект исчез сам — перечитайте расписку"


# ═══════════════════════════════════════════════════════════════════════
# 3. Расписка точна: после её снятия остаётся РОВНО текст автора
# ═══════════════════════════════════════════════════════════════════════
ДОБАВКИ_ПРИМЕР = [
    ("context", "Контекст", "‹назовите файл/путь через @›"),
    ("verification", "Проверка", "‹тест, и чинить, пока не пройдёт›"),
    ("note", "Краткость", "Ответь кратко."),
]


@pytest.mark.parametrize("family,use_xml", [
    ("claude", True),      # XML-сборка: обёртка вокруг текста автора — тоже наша
    ("claude", False),     # «Метка: текст»
    ("openai", False),     # «## Метка\nтекст»
])
@pytest.mark.parametrize("добавки", [ДОБАВКИ_ПРИМЕР, []], ids=["с_добавками", "без_добавок"])
def test_снятие_расписки_возвращает_текст_автора(family, use_xml, добавки):
    """Контракт расписки в одну строку — и он держит оба дефекта разом.

    Первая редакция оставляла XML-обёртку за пределами расписки («это не
    добавленное содержание, а переупаковка»), и слэш в закрывающем теге тут же
    прошёл как «путь к файлу» в `_PATH`: самопроверка отчиталась, что
    `claude-scope` закрыто, хотя файл автор так и не назвал. Исключений в
    расписке быть не должно — этот тест их и не допускает.
    """
    core = "Почини баг в @a.py и прогони тесты"
    improved, расписка = _assemble(core, добавки, family, use_xml)
    assert strip_insertions(improved, расписка) == core


@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_после_вычитания_расписки_наших_слов_не_остаётся(промпт, причина, модель):
    """На живых промптах: в тексте, который видит второй прогон, нет ни одного
    слова, которого не было бы у автора.

    Сравнение по словам, а не по подстрокам: подстрочный список («нет
    „Контекст:“, нет „Ответь кратко“») пришлось бы править вместе с каждой
    новой добавкой — и он молча устарел бы, как устаревают все такие списки.
    """
    отчёт = build_report(промпт, модель)
    текст = strip_insertions(отчёт["improved"], отчёт["insertions"])
    лишние = _слова(текст) - _слова(отчёт["original"])
    assert not лишние, "%s | наши слова доехали до второго прогона: %s" % (причина, лишние)
    assert "‹" not in текст, "плейсхолдер остался в тексте автора"


def test_расписка_переживает_json():
    """Отчёт ходит наружу через `--json`, и там кортежи становятся списками.

    Самопроверка обязана работать и по такому отчёту: иначе `--json --verify`
    и потребитель, который сохранил отчёт и вернулся к нему позже, получили бы
    разные корзины.
    """
    отчёт = build_report("ОБЯЗАТЕЛЬНО почини @a.py и прогони тесты", "claude-opus-5")
    сквозь_json = json.loads(json.dumps(отчёт, ensure_ascii=False))
    assert verify_delta(сквозь_json) == verify_delta(отчёт)


# ═══════════════════════════════════════════════════════════════════════
# 4. Второй прогон не переопределяет модель и ничего не портит в отчёте
# ═══════════════════════════════════════════════════════════════════════
def test_второй_прогон_не_зовёт_детект_модели(monkeypatch):
    """`detect.resolve` читает env и конфиги: между двумя половинами
    самопроверки он вправе вернуть другое семейство (сменилась переменная
    среды, поправили ~/.claude/settings.json). Тогда корзины сравнивали бы
    находки по РАЗНЫМ наборам правил, и расхождение выглядело бы дефектом
    инструмента, которым оно не является.
    """
    отчёт = build_report("Почини баг в @a.py и прогони тесты", "claude-opus-5")

    def взорвись(*args, **kwargs):
        raise AssertionError("detect.resolve позван во втором прогоне")

    monkeypatch.setattr(_detect, "resolve", взорвись)
    корзины = verify_delta(отчёт)
    assert set(корзины) == {"closed", "left", "introduced"}


def test_готовый_target_отменяет_детект(monkeypatch):
    """Тот же параметр отдельно от самопроверки: передан `target` — резолва нет."""
    def взорвись(*args, **kwargs):
        raise AssertionError("detect.resolve позван при готовом target")

    monkeypatch.setattr(_detect, "resolve", взорвись)
    отчёт = build_report("Почини баг в @a.py",
                         target={"family": "claude", "generation": "opus-5",
                                 "model_id": "claude-opus-5"})
    assert отчёт["target"]["family"] == "claude"
    assert отчёт["improved"]


def test_прежние_формы_вызова_живы():
    """Совместимость: у людей вызов уже прописан в settings.json.

    Обе прежние формы обязаны работать как работали — новый параметр только
    третий и только с умолчанием.
    """
    позиционно = build_report("Почини баг в @a.py", "claude-opus-5")
    именованно = build_report("Почини баг в @a.py", model="claude-opus-5")
    assert позиционно["improved"] == именованно["improved"]
    assert позиционно["target"]["family"] == "claude"


def test_самопроверка_не_трогает_отчёт():
    """Чистая функция: отчёт после неё побайтово тот же."""
    отчёт = build_report("Не мог бы ты ОБЯЗАТЕЛЬНО починить @a.py", "claude-opus-5")
    снимок = json.dumps(отчёт, ensure_ascii=False, sort_keys=True)
    verify_delta(отчёт)
    assert json.dumps(отчёт, ensure_ascii=False, sort_keys=True) == снимок


def test_отчёт_без_модели_не_роняет_самопроверку():
    """Модель не определилась — сравнивать нечего, но падать тоже нельзя."""
    assert verify_delta(ОТЧЁТ_БЕЗ_МОДЕЛИ) == {"closed": [], "left": [], "introduced": []}


# ═══════════════════════════════════════════════════════════════════════
# 5. Вывод: счёт правил, а не оценка качества; флаг ничего не ломает
# ═══════════════════════════════════════════════════════════════════════
def test_вывод_не_оценивает_качество():
    """Инструмент не умеет говорить «стало лучше» и не берётся.

    Он считает СВОИ ЖЕ правила: сколько горело до и сколько после. Любая цифра
    со знаком качества («лучше на 40%») была бы выдумкой поверх этого счёта —
    ровно тем, чего проект не делает нигде.
    """
    текст = render_verify({"closed": ["claude-dial-caps"], "left": ["claude-scope"],
                           "introduced": ["claude-xml"]})
    assert "лучше" not in текст.lower(), текст
    assert "%" not in текст, текст
    assert "закрыто 1, оставлено вам 1, внесено инструментом 1" in текст


def test_флаг_только_дописывает_блок_в_конец(capsys):
    """Без `--verify` вывод прежний до символа, с ним — тот же плюс хвост."""
    from nativeprompt.__main__ import main

    аргументы = ["improve", "ОБЯЗАТЕЛЬНО почини @a.py и прогони тесты",
                 "--model", "claude-opus-5"]
    assert main(аргументы) == 0
    без = capsys.readouterr().out
    assert main(аргументы + ["--verify"]) == 0
    с_флагом = capsys.readouterr().out
    assert "САМОПРОВЕРКА" not in без
    assert с_флагом.startswith(без), "самопроверка сдвинула прежний вывод"
    assert "САМОПРОВЕРКА" in с_флагом
    for подпись in ("закрыто", "оставлено вам", "внесено инструментом"):
        assert подпись in с_флагом


def test_json_получает_корзины_только_с_флагом(capsys):
    from nativeprompt.__main__ import main

    аргументы = ["improve", "Почини баг в @a.py", "--model", "claude-opus-5", "--json"]
    assert main(аргументы) == 0
    без = json.loads(capsys.readouterr().out)
    assert "verify" not in без, "без флага отчёт прежний"
    assert main(аргументы + ["--verify"]) == 0
    с_флагом = json.loads(capsys.readouterr().out)
    assert с_флагом["verify"] == verify_delta(без)
    # Остальной отчёт при этом не поехал.
    assert {k: v for k, v in с_флагом.items() if k != "verify"} == без
