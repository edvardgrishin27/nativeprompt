# 2. Карточка ничего не считает сама
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_карточка_сходится_с_отчётом(промпт, причина, модель):
    """Второе вычисление того же — это второй источник правды, а он разойдётся.

    Проект уже горел на двух копиях одной регулярки и двух копиях одного
    символа-плейсхолдера. Карточка обязана быть выпиской из отчёта, а не
    параллельным разбором.
    """
    отчёт = build_report(промпт, модель)
    карточка, цель = отчёт["meta"], отчёт["target"]
    метка = "%s | %s" % (причина, модель)
    assert карточка["shape"] == отчёт["shape"], метка
    assert карточка["findings"] == [f["id"] for f in отчёт["findings"]], метка
    assert карточка["applied"] == list(отчёт["applied"]), метка
    assert карточка["family"] == цель["family"], метка
    assert карточка["generation"] == (цель.get("generation") or "—"), метка
    assert карточка["generation_source"] == цель["generation_source"], метка


def test_карточка_собирается_из_готового():
    """`build_meta` — чистая функция от того, что ей передали.

    Ни детекта, ни разбора внутри: передайте другие аргументы — получите ровно
    их, без похода в окружение.
    """
    цель = {"family": "claude", "generation": "opus-5", "generation_source": "model-id"}
    карточка = build_meta("Почини баг", цель, "trivial",
                          [{"id": "claude-scope"}], ["claude-scope"])
    assert карточка["shape"] == "trivial"
    assert карточка["findings"] == ["claude-scope"]
    assert карточка["applied"] == ["claude-scope"]
    assert карточка["generation"] == "opus-5"
    # И она не мутирует переданное.
    assert цель == {"family": "claude", "generation": "opus-5",
                    "generation_source": "model-id"}


