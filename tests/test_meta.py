# 3. Хэш промпта
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_хэш_стабилен_между_прогонами(промпт, причина):
    первый = build_report(промпт, "claude-opus-5")["meta"]["prompt_sha256"]
    второй = build_report(промпт, "claude-opus-5")["meta"]["prompt_sha256"]
    assert первый == второй, причина
    assert len(первый) == 12 and re.fullmatch(r"[0-9a-f]{12}", первый), первый


@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_хэш_меняется_от_одного_символа(промпт, причина):
    """Один символ в конце — уже другой промпт, и карточка обязана это показать."""
    было = build_report(промпт, "claude-opus-5")["meta"]["prompt_sha256"]
    стало = build_report(промпт + "!", "claude-opus-5")["meta"]["prompt_sha256"]
    assert было != стало, "%s: правка на символ не изменила хэш" % причина


def test_хэш_считается_от_текста_который_видели_детекторы():
    """От `original`, а не от сырого аргумента.

    Иначе две двери CLI (аргумент и stdin) давали бы разный хэш на одном и том
    же промпте — тот самый класс расхождения, который уже чинили в
    `normalize_prompt`.
    """
    промпт = "  Почини баг в @src/auth.py и прогони тесты  \r\n"
    отчёт = build_report(промпт, "claude-opus-5")
    ожидаемый = hashlib.sha256(отчёт["original"].encode("utf-8")).hexdigest()[:12]
    assert отчёт["meta"]["prompt_sha256"] == ожидаемый
    assert отчёт["meta"]["prompt_sha256"] != hashlib.sha256(
        промпт.encode("utf-8")).hexdigest()[:12], "хэш взят от ненормализованного текста"


def test_обе_двери_cli_дают_один_хэш():
    """Аргумент и stdin — один промпт, значит одна карточка."""
    промпт = "    ВАЖНО = load_config()\nПочини загрузку конфига и прогони тесты"
    общее = [sys.executable, "-m", "nativeprompt", "improve",
             "--model", "claude-opus-5", "--json"]
    через_аргумент = subprocess.run(общее + [промпт], capture_output=True, text=True,
                                    cwd=str(_КОРЕНЬ), check=True)
    через_stdin = subprocess.run(общее, input=промпт, capture_output=True, text=True,
                                 cwd=str(_КОРЕНЬ), check=True)
    a = json.loads(через_аргумент.stdout)["meta"]
    b = json.loads(через_stdin.stdout)["meta"]
    assert a["prompt_sha256"] == b["prompt_sha256"], (a["prompt_sha256"], b["prompt_sha256"])
    assert a == b


