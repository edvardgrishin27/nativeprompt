# 6. Два выхода: строка человеку, объект машине
# ═══════════════════════════════════════════════════════════════════════
def test_строка_карточки_одна_и_несёт_главное():
    отчёт = build_report("Не мог бы ты ОБЯЗАТЕЛЬНО поправить вывод в @src/report.py?",
                         "claude-opus-5")
    строка = render_meta(отчёт["meta"])
    assert строка.startswith("воспроизводимость: nativeprompt ")
    for кусок in (nativeprompt.__version__, отчёт["meta"]["rules_version"],
                  отчёт["meta"]["prompt_sha256"], отчёт["meta"]["shape"],
                  отчёт["meta"]["generation_source"]):
        assert кусок in строка, (кусок, строка)
    # Списки id в строку не идут: они уже напечатаны выше, каждый со ссылкой на
    # правило, и вторая копия — шум, а не воспроизводимость.
    for rule_id in отчёт["meta"]["findings"]:
        assert rule_id not in строка, rule_id


def test_строка_карточки_в_человекочитаемом_выводе():
    готово = subprocess.run(
        [sys.executable, "-m", "nativeprompt", "improve",
         "Не мог бы ты ОБЯЗАТЕЛЬНО поправить вывод в @src/report.py?",
         "--model", "claude-opus-5"],
        capture_output=True, text=True, cwd=str(_КОРЕНЬ), check=True)
    начала = [с for с in готово.stdout.splitlines() if с.startswith("воспроизводимость:")]
    assert len(начала) == 1, начала
    # Стоит в шапке, ДО мета-промпта: человек выделяет мета-промпт целиком и
    # копирует своей модели, и строка про версии уехала бы вместе с ним.
    assert готово.stdout.index("воспроизводимость:") < готово.stdout.index("МЕТА-ПРОМПТ")


def test_полный_объект_в_json():
    готово = subprocess.run(
        [sys.executable, "-m", "nativeprompt", "improve", "Почини баг в @src/auth.py",
         "--model", "claude-opus-5", "--json"],
        capture_output=True, text=True, cwd=str(_КОРЕНЬ), check=True)
    карточка = json.loads(готово.stdout)["meta"]
    assert set(карточка) == set(СКАЛЯРЫ) | set(СПИСКИ), sorted(карточка)


def test_карточка_переживает_json():
    """Отчёт прикладывают к баг-репорту — значит он обязан сериализоваться."""
    отчёт = build_report("Почини баг в @src/auth.py", "claude-opus-5")
    туда_обратно = json.loads(json.dumps(отчёт, ensure_ascii=False))
    assert туда_обратно["meta"] == отчёт["meta"]
