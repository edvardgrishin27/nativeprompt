# 5. Поколение и признак, включая alias-unresolved
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("модель,поколение,признак", [
    ("claude-opus-5", "opus-5", "model-id"),
    ("claude-fable-5", "fable-5", "model-id"),
    ("gpt-5.6", "gpt-5.6", "model-id"),
    # Алиас без версии: правила применяются СЕМЕЙСТВА, и карточка обязана это
    # показать. Без признака такой отчёт неотличим от отчёта по точно
    # названной модели — а получен он по другому набору правил.
    ("opus", "—", "alias-unresolved"),
    ("sonnet", "—", "alias-unresolved"),
])
def test_признак_поколения_назван_честно(модель, поколение, признак):
    карточка = build_report("Не мог бы ты починить баг в логине", модель)["meta"]
    assert карточка["generation"] == поколение, карточка
    assert карточка["generation_source"] == признак, карточка


def test_два_разных_прогона_различимы_по_карточке():
    """Ради чего всё: разные условия дают разные карточки."""
    один = build_report("Почини баг в @src/auth.py", "claude-opus-5")["meta"]
    другой = build_report("Почини баг в @src/auth.py", "gpt-5.6")["meta"]
    третий = build_report("Почини баг в @src/authz.py", "claude-opus-5")["meta"]
    assert один != другой, "две модели дали одинаковую карточку"
    assert один["family"] != другой["family"]
    assert один["prompt_sha256"] != третий["prompt_sha256"], "два промпта — один хэш"


