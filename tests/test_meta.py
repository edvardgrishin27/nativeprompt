# 4. Версии — из файлов, а не из памяти
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("семейство", sorted(catalog.available_families()))
def test_версия_правил_равна_значению_в_файле(семейство):
    путь = _КОРЕНЬ / "nativeprompt" / "rules" / ("%s.json" % семейство)
    из_файла = json.loads(io.open(путь, encoding="utf-8").read())["rules_version"]
    карточка = build_meta("Почини баг", {"family": семейство}, "normal", [], [])
    assert карточка["rules_version"] == из_файла, (семейство, карточка["rules_version"])


def test_дата_снимка_доков_равна_манифесту():
    """Дата снимка — версия `rules/_sources.json`, против которого диффает update.

    Она общая на все семейства и отвечает на другой вопрос, чем `rules_version`:
    та говорит, когда человек правил правила, эта — к какому дню относится
    сверка со страницами вендора. Разошлись — значит доки перечитывали, а
    правила не трогали, и по одному отчёту это видно.
    """
    из_манифеста = catalog.load_sources()["rules_version"]
    for семейство in catalog.available_families():
        карточка = build_meta("Почини баг", {"family": семейство}, "normal", [], [])
        assert карточка["docs_snapshot"] == из_манифеста, семейство


def test_версия_пакета_не_разъезжается_с_pyproject():
    """Карточка называет версию инструмента — значит она обязана быть верной."""
    отчёт = build_report("Почини баг в @src/auth.py", "claude-opus-5")
    assert отчёт["meta"]["tool_version"] == nativeprompt.__version__
    текст = io.open(_КОРЕНЬ / "pyproject.toml", encoding="utf-8").read()
    m = re.search(r'^version = "([^"]+)"', текст, re.M)
    assert m, "в pyproject.toml пропала версия"
    assert m.group(1) == nativeprompt.__version__, (
        "pyproject обещает %s, пакет живёт под %s" % (m.group(1), nativeprompt.__version__))


