"""Карточка воспроизводимости: по чему именно получен ЭТОТ отчёт.

Два отчёта от разных версий инструмента и разных версий шпаргалки внешне
неразличимы: та же шапка, тот же список советов, те же ссылки. Через месяц
человек не отличит вывод, собранный до правки правил, от вывода после неё, и
спор «у меня выдавало другое» не решается ничем — сравнивать нечего.

Условия получения дописываются в сам артефакт, а не держатся в голове
у запускавшего.

Новых данных карточка не считает НИ ОДНОГО: версия пакета, версия правил,
поколение и признак, по которому оно определилось, форма задачи, списки id —
всё это пайплайн уже посчитал и просто не печатал. Единственное вычисление —
sha256 промпта, и оно есть в стандартной библиотеке.

Здесь пять граней:

    1. поля заполнены — на всём корпусе × три модели, и списки не вырождены;
    2. карточка не считает сама — каждое поле сходится с тем местом отчёта,
       откуда взято, иначе она рассказывает о другом отчёте;
    3. хэш стабилен между прогонами и меняется от одного символа;
    4. версия правил равна значению в файле правил, версия пакета — версии
       пакета (и та же, что в pyproject);
    5. поколение и признак не врут, включая `alias-unresolved`.
"""

from __future__ import annotations

import hashlib
import io
import json
import pathlib
import re
import subprocess
import sys

import pytest

import nativeprompt
from nativeprompt import catalog
from nativeprompt.explain import build_meta, build_report, render_meta

from test_invariant import КОРПУС, МОДЕЛИ

_КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
_ИМЕНА = [f"{i:02d}_{c[:36]}" for i, (_, c) in enumerate(КОРПУС)]

#: Поля-скаляры: пустых среди них быть не может — пустое поле в карточке
#: воспроизводимости означает, что воспроизвести по ней нельзя.
СКАЛЯРЫ = ("tool_version", "family", "rules_version", "docs_snapshot",
           "generation", "generation_source", "shape", "prompt_sha256")

#: Поля-списки. Их пустота — это ДАННЫЕ, а не пропуск: промпт, на котором не
#: сработало ни одного правила, честно даёт пустой список, и требовать от него
#: непустоты значило бы требовать находок там, где их нет. Поэтому здесь
#: проверяется тип и осмысленность содержимого, а вырождение (всегда пусто на
#: всём корпусе) ловится отдельным тестом ниже.
СПИСКИ = ("findings", "applied")


def _все_карточки():
    for промпт, причина in КОРПУС:
        for модель in МОДЕЛИ:
            отчёт = build_report(промпт, модель)
            yield отчёт, "%s | %s" % (причина, модель)


# ═══════════════════════════════════════════════════════════════════════
# 1. Поля заполнены
# ═══════════════════════════════════════════════════════════════════════
@pytest.mark.parametrize("модель", МОДЕЛИ)
@pytest.mark.parametrize("промпт,причина", КОРПУС, ids=_ИМЕНА)
def test_карточка_заполнена_на_любом_корпусном_промпте(промпт, причина, модель):
    отчёт = build_report(промпт, модель)
    карточка = отчёт["meta"]
    метка = "%s | %s" % (причина, модель)
    assert set(карточка) == set(СКАЛЯРЫ) | set(СПИСКИ), (метка, sorted(карточка))
    for поле in СКАЛЯРЫ:
        значение = карточка[поле]
        assert isinstance(значение, str) and значение.strip(), (метка, поле, значение)
    известные = {r["id"] for r in catalog.load_family(карточка["family"])["rules"]}
    for поле in СПИСКИ:
        assert isinstance(карточка[поле], list), (метка, поле)
        чужие = set(карточка[поле]) - известные
        assert not чужие, "%s: в %s id не из шпаргалки: %s" % (метка, поле, sorted(чужие))
    assert set(карточка["applied"]) <= set(карточка["findings"]), (
        "%s: применено правило, которое не срабатывало" % метка)


def test_списки_не_вырождены():
    """Карточка, у которой списки всегда пусты, прошла бы проверку типов.

    Поэтому отдельно: на корпусе оба списка где-то непусты, иначе поле есть, а
    смысла в нём нет.
    """
    непустые = {поле: 0 for поле in СПИСКИ}
    for отчёт, _ in _все_карточки():
        for поле in СПИСКИ:
            if отчёт["meta"][поле]:
                непустые[поле] += 1
    for поле, сколько in непустые.items():
        assert сколько, "поле %s пусто на всём корпусе" % поле


def test_у_отчёта_с_ошибкой_карточки_нет():
    """Половина карточки хуже её отсутствия: она обещает то, чего не даёт.

    Без семейства нет ни версии правил, ни поколения, ни разбора — так же
    здесь ведут себя `findings` и `improved`, и карточка не исключение.
    """
    отчёт = build_report("Почини баг в авторизации", "несуществующая-модель-9000")
    assert отчёт.get("error") == "model_unknown"
    assert "meta" not in отчёт


