"""Правила Claude Fable 5.1 и детекторы под них.

Fable 5.1 отличается от Fable 5 поведением, а не API, и одно отличие
перевёрнутое: прошлые модели ЗЛОУПОТРЕБЛЯЛИ списками и жирным, из-за чего
в промптах накопились запреты «без списков». Fable 5.1 форматирует МЕНЬШЕ,
и старый запрет теперь работает против автора. Такое правило легко сломать
незаметно, поэтому детекторы проверяются на парах: где обязан сработать
и где обязан промолчать.
"""

import json
import os

import pytest

from nativeprompt.analyze import _CHECKS, task_shape
from nativeprompt.explain import build_report
from nativeprompt import detect

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def чек(имя, текст):
    return bool(_CHECKS[имя](текст, текст.lower(), {}))


# ── antiformatting ──────────────────────────────────────────────────

@pytest.mark.parametrize("текст", [
    "пиши без списков и заголовков",
    "не используй жирный шрифт",
    "no bullet points please",
    "avoid markdown formatting",
    "минимум разметки в ответе",
    "никаких заголовков",
])
def test_запрет_форматирования_виден(текст):
    assert чек("antiformatting", текст), "не увидел запрет: %r" % текст


@pytest.mark.parametrize("текст", [
    "сделай ответ списком",
    "добавь заголовки к разделам",
    "выдели жирным главное",
    "почини баг в авторизации",
    "оформи таблицей",
])
def test_просьба_форматировать_не_путается_с_запретом(текст):
    """Самый опасный класс ошибки: сработать на промпте, где всё в порядке.

    «Сделай списком» и «без списков» отличаются одним словом, и грубая
    регулярка на слове «список» сожгла бы половину нормальных промптов.
    """
    assert not чек("antiformatting", текст), "ложное срабатывание: %r" % текст


# ── long_task ───────────────────────────────────────────────────────

@pytest.mark.parametrize("текст", [
    "сделай рефакторинг модуля, разбей на слои, перенеси тесты и обнови документацию",
    "добавь логирование, потом прогони тесты",
    "пройди по всем файлам и исправь импорты, и так пока не станет зелено",
    "напиши миграцию, затем проверь на копии базы",
])
def test_многошаговая_задача_видна(текст):
    assert чек("long_task", текст), "не увидел многошаговость: %r" % текст


@pytest.mark.parametrize("текст", [
    "почини опечатку в README",
    "напиши функцию сортировки",
    "объясни, что делает этот код",
])
def test_короткая_просьба_не_считается_длинной(текст):
    """Иначе подсказка «доделай до конца» полезет в каждый второй промпт."""
    assert not чек("long_task", текст), "ложное срабатывание: %r" % текст


# ── code_task ───────────────────────────────────────────────────────

def test_код_отличается_от_не_кода():
    assert чек("code_task", "почини баг в функции авторизации и добавь тест")
    assert not чек("code_task", "напиши поздравление сестре с днём рождения")


def test_пустяк_не_требует_ограничения_области():
    """На опечатке очерчивать границы правки незачем: правило только шумит."""
    assert task_shape("почини опечатку") == "trivial"
    assert not чек("code_task", "почини опечатку")


# ── правила и поколение ─────────────────────────────────────────────

def test_поколение_5_1_не_матчится_как_5():
    """Порядок в словаре поколений значим: 'fable-5' — префикс 'fable-5-1'."""
    # Без префикса семейства модель не опознаётся вовсе, и это верно:
    # голое «fable-5-1» может быть чем угодно.
    for ident in ("claude-fable-5-1", "claude-fable-5.1"):
        r = detect.resolve(explicit=ident)
        assert r.get("generation") == "fable-5-1", "%s → %s" % (ident, r.get("generation"))
    assert detect.resolve(explicit="claude-fable-5").get("generation") == "fable-5"


def test_правила_5_1_живут_только_на_своем_поколении():
    """Иначе советы 5.1 полезут в промпты для Fable 5, где они неверны."""
    текст = "разбери модуль, потом прогони тесты"
    свои = [f["id"] for f in build_report(
        текст, target=detect.resolve(explicit="claude-fable-5-1"))["findings"]]
    чужие = [f["id"] for f in build_report(
        текст, target=detect.resolve(explicit="claude-fable-5"))["findings"]]
    assert any(i.startswith("fable51-") for i in свои), "на 5.1 нет ни одного своего правила"
    assert not any(i.startswith("fable51-") for i in чужие), "правила 5.1 протекли на Fable 5"


def test_у_правил_5_1_есть_живой_источник():
    d = json.load(open(os.path.join(КОРЕНЬ, "nativeprompt", "rules", "claude.json"),
                       encoding="utf-8"))
    свои = [r for r in d["rules"] if r["id"].startswith("fable51-")]
    assert len(свои) >= 4, "правил 5.1 меньше, чем добавляли"
    for r in свои:
        assert r["source"].startswith("https://platform.claude.com/"), r["id"]
        assert "prompting-claude-fable-5-1" in r["source"], (
            "%s ссылается не на страницу 5.1: %s" % (r["id"], r["source"]))
